namespace {
// ID provided by the client to make a vtc registration unique per client.
using ClientId = uint64_t;

// ID generated by this AGIS fidl service for each vtc registration.
using GlobalId = uint32_t;

using GetVulkanSocketCompleter =
    fidl::Server<fuchsia_gpu_agis::ComponentRegistry>::GetVulkanSocketCompleter;

// Value struct for |registry| map.
struct Entry {
  Entry(GlobalId global_id_in, std::string process_name_in, zx_koid_t process_koid_in,
        zx::socket vulkan_socket_in)
      : global_id(global_id_in),
        process_name(std::move(process_name_in)),
        process_koid(process_koid_in),
        vulkan_socket(vulkan_socket_in.release()) {}
  GlobalId global_id;
  std::string process_name;
  zx_koid_t process_koid;
  zx::socket vulkan_socket;
  // Set while a GetVulkanSocket() hanging get is pending.
  std::optional<GetVulkanSocketCompleter::Async> vulkan_socket_completer;
};

// The global registry that maps global ids to |Entry|s. Valid global ids are greater
// than zero.
std::unordered_map<GlobalId, std::shared_ptr<Entry>> registry;

// Erase a registered |id| from |registry|.
bool EraseEntry(ClientId id, std::unordered_map<ClientId, std::shared_ptr<Entry>> *session) {
  // Find |id| in the session.
  auto session_iter = session->find(id);
  if (session_iter == session->end())
    return false;
  auto global_id = session_iter->second->global_id;
  session->erase(session_iter);

  // Remove |global_id| from the |registry|.
  auto registry_iter = registry.find(global_id);
  if (registry_iter == registry.end())
    return false;
  registry.erase(registry_iter);

  return true;
}

bool PeerEndpointIsOpen(const zx::socket &endpoint) {
  if (!endpoint.is_valid()) {
    return false;
  }
  auto status =
      zx_object_wait_one(endpoint.get(), ZX_SOCKET_PEER_CLOSED, ZX_TIME_INFINITE_PAST, nullptr);

  if (status == ZX_ERR_TIMED_OUT) {
    return true;
  }

  // Report abnormal status for remaining possible return values.
  if (!(status == ZX_OK || status == ZX_ERR_CANCELED)) {
    FX_LOG_KV(ERROR, "PeerEndpointIsOpen", FX_KV("status", status));
  }

  return false;
}

}  // namespace

//
// Register and unregister Vulkan traceable components.
//
class ComponentRegistryImpl final : public fidl::Server<fuchsia_gpu_agis::ComponentRegistry> {
 public:
  ~ComponentRegistryImpl() override {
    for (auto session_pair : session_) {
      auto global_id = session_pair.second->global_id;
      auto i = registry.find(global_id);
      if (i == registry.end()) {
        FX_LOG_KV(ERROR, "Corrupt registry");
      }
      registry.erase(global_id);
    }
  }

  // Add entries to the |registry| map.
  void Register(RegisterRequest &request, RegisterCompleter::Sync &completer) override {
    // Test if the vtc map is full.
    if (registry.size() == fuchsia_gpu_agis::kMaxVtcs) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kVtcsExceeded));
      return;
    }

    // Verify that the |id| is unique.
    {
      auto i = session_.find(request.id());
      if (i != session_.end()) {
        completer.Reply(fit::error(fuchsia_gpu_agis::Error::kAlreadyRegistered));
        return;
      }
    }

    GlobalId global_id = rand();
    while (registry.find(global_id) != registry.end() || global_id == 0) {
      global_id = rand();
    }

    // Update registry database.
    {
      auto e = std::make_shared<Entry>(global_id, request.process_name(), request.process_koid(),
                                       zx::socket() /* vulkan_socket */);
      registry.insert(std::make_pair(global_id, e));
      session_.insert(std::make_pair(request.id(), e));
    }

    completer.Reply(fit::ok());
  }

  void Unregister(UnregisterRequest &request, UnregisterCompleter::Sync &completer) override {
    if (!EraseEntry(request.id(), &session_)) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kNotFound));
      return;
    }
    completer.Reply(fit::ok());
  }

  void GetVulkanSocket(GetVulkanSocketRequest &request,
                       GetVulkanSocketCompleter::Sync &completer) override {
    auto session_iter = session_.find(request.id());
    if (session_iter == session_.end()) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kNotFound));
      return;
    }

    auto &entry = session_iter->second;
    if (entry->vulkan_socket_completer.has_value()) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kAlreadyRegistered));
      return;
    }

    if (!entry->vulkan_socket.is_valid()) {
      // Initializing this vulkan_socket_completer field means the reply is pending and will
      // be satisfied when Connector::GetSocket() is called.  This is the hanging get.
      entry->vulkan_socket_completer = completer.ToAsync();
      return;
    }

    // |vulkan_socket| handle is valid, verify that the other endpoint is open.
    if (!PeerEndpointIsOpen(entry->vulkan_socket)) {
      // No longer open so re-register our completer.  It will now be
      // pending and is satisfied when Connector::() is called.
      entry->vulkan_socket_completer = completer.ToAsync();
      return;
    }

    // We were able to respond with a valid |vulkan_socket| so send the response.
    completer.Reply(fit::ok(fuchsia_gpu_agis::ComponentRegistryGetVulkanSocketResponse{
        {.socket = std::move(entry->vulkan_socket)}}));
  }

 private:
  std::unordered_map<ClientId, std::shared_ptr<Entry>> session_;
};

//
// Retrieve the list of available, registered Vulkan traceable components.
//
class ObserverImpl final : public fidl::Server<fuchsia_gpu_agis::Observer> {
 public:
  void Vtcs(VtcsCompleter::Sync &completer) override {
    std::vector<fuchsia_gpu_agis::Vtc> vtcs;
    for (const auto &pair : registry) {
      vtcs.emplace_back(fuchsia_gpu_agis::Vtc{{
          .global_id = pair.first,
          .process_koid = pair.second->process_koid,
          .process_name = pair.second->process_name,
      }});
    }
    completer.Reply(fit::ok(fuchsia_gpu_agis::ObserverVtcsResponse{{.vtcs = std::move(vtcs)}}));
  }
};

//
// Create a Zircon socket to establish connectivity to a Vulkan traceable component.
//
class ConnectorImpl final : public fidl::Server<fuchsia_gpu_agis::Connector> {
 public:
  void GetSocket(GetSocketRequest &request, GetSocketCompleter::Sync &completer) override {
    auto registry_iter = registry.find(request.global_id());
    if (registry_iter == registry.end()) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kNotFound));
      return;
    }

    auto &entry = registry_iter->second;
    if (entry->vulkan_socket.is_valid()) {
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kAlreadyRegistered));
      return;
    }

    // Create both socket endpoints if they haven't been initialized yet.
    zx::socket ffx_socket;
    auto status = zx::socket::create(0u, &entry->vulkan_socket, &ffx_socket);
    if (status != ZX_OK) {
      FX_LOG_KV(ERROR, "zx::socket::create() failed", FX_KV("status", status));
      completer.Reply(fit::error(fuchsia_gpu_agis::Error::kInternalError));
      return;
    }

    // Satisfy hanging get for retrieval of the vulkan socket end.
    if (entry->vulkan_socket_completer.has_value()) {
      entry->vulkan_socket_completer->Reply(
          fit::ok(fuchsia_gpu_agis::ComponentRegistryGetVulkanSocketResponse{
              {.socket = std::move(entry->vulkan_socket)}}));
      entry->vulkan_socket_completer.reset();
    }

    completer.Reply(
        fit::ok(fuchsia_gpu_agis::ConnectorGetSocketResponse{{.socket = std::move(ffx_socket)}}));
  }
};

int main(int argc, const char **argv) {
  async::Loop loop(&kAsyncLoopConfigAttachToCurrentThread);
  async_dispatcher_t *dispatcher = loop.dispatcher();
  srand(static_cast<unsigned int>(time(nullptr)));
  fuchsia_logging::LogSettingsBuilder builder;
  builder.WithTags({"agis"}).BuildAndInitialize();

  component::OutgoingDirectory outgoing(dispatcher);
  zx::result<> result = outgoing.ServeFromStartupInfo();
  if (result.is_error()) {
    FX_LOG_KV(ERROR, "Failed to serve outgoing directory", FX_KV("status", result.status_value()));
    return 1;
  }

  // Each connection gets its own server instance, owned by its binding, so that a client's
  // registrations are removed when it disconnects.
  result = outgoing.AddUnmanagedProtocol<fuchsia_gpu_agis::ComponentRegistry>(
      [dispatcher](fidl::ServerEnd<fuchsia_gpu_agis::ComponentRegistry> server_end) {
        fidl::BindServer(dispatcher, std::move(server_end),
                         std::make_unique<ComponentRegistryImpl>());
      });
  if (result.is_error()) {
    FX_LOG_KV(ERROR, "Failed to add ComponentRegistry", FX_KV("status", result.status_value()));
    return 1;
  }
  result = outgoing.AddUnmanagedProtocol<fuchsia_gpu_agis::Observer>(
      [dispatcher](fidl::ServerEnd<fuchsia_gpu_agis::Observer> server_end) {
        fidl::BindServer(dispatcher, std::move(server_end), std::make_unique<ObserverImpl>());
      });
  if (result.is_error()) {
    FX_LOG_KV(ERROR, "Failed to add Observer", FX_KV("status", result.status_value()));
    return 1;
  }
  result = outgoing.AddUnmanagedProtocol<fuchsia_gpu_agis::Connector>(
      [dispatcher](fidl::ServerEnd<fuchsia_gpu_agis::Connector> server_end) {
        fidl::BindServer(dispatcher, std::move(server_end), std::make_unique<ConnectorImpl>());
      });
  if (result.is_error()) {
    FX_LOG_KV(ERROR, "Failed to add Connector", FX_KV("status", result.status_value()));
    return 1;
  }

  return loop.Run();
}
