set -e

# Generates 25 synthesized ELF components, each linking a bunch of dynamic libraries.
#
# Run it like:
#
# src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/components/generate_components.sh

# Change to the script's containing directory
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
cd "$SCRIPT_DIR"

for N in $(seq 1 25); do
  N=$(printf "%02d" "$N")
  DIR="test_component_${N}"

  # Remove existing directory if it exists
  if [ -d "$DIR" ]; then
    rm -rf "$DIR"
  fi

  mkdir "$DIR"

  # Generate BUILD.bazel
  cat <<EOL > "$DIR/BUILD.bazel"
# Copyright 2026 The Fuchsia Authors. All rights reserved.
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

# Generated by $0

load(
    "//build/bazel/rules/cc:fx_cc_test_binary.bzl",
    "fx_cc_test_binary",
)
load(
    "//build/bazel/rules/components:fx_component.bzl",
    "fx_component",
    "fx_component_manifest",
)
load(
    "//build/bazel/rules/packages:fx_package.bzl",
    "fx_package",
)
load(
    "//build/bazel/rules/packages:fx_packaged_binary.bzl",
    "fx_packaged_binary",
)

package(default_applicable_licenses = ["//:license"])

# Preserve GN output_dir = target_out_dir and ../../dylibs group dependency on cc_test_executable.
# @bazel2gn:raw_attribute:output_dir = target_out_dir
# @bazel2gn:raw_attribute:deps += [ "../../dylibs" ]
fx_cc_test_binary(
    name = "test_component_${N}_bin",
    srcs = ["main.cc"],
    # In Bazel, cc_binary links fx_cc_shared_library targets via dynamic_deps;
    # GN depends on the ../../dylibs group via deps instead.
    # TODO(https://fxbug.dev/570694755): Support dynamic_deps on fx_cc_test_binary in bazel2gn.
    # @bazel2gn:skip
    dynamic_deps = [
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_1",
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_2",
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_3",
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_4",
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_5",
    ],
    gn_output_name = "test_component_${N}",
    deps = [
        "//examples/components/routing/fidl:echo_cpp",
        "//sdk/lib/component/incoming/cpp",
        # In Bazel, fx_cc_library targets provide the headers for dynamic_deps;
        # GN gets these via ../../dylibs.
        # TODO(https://fxbug.dev/570694755): Propagate CcInfo from fx_cc_shared_library.
        # @bazel2gn:skip
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_1:lib",
        # In Bazel, fx_cc_library provides headers for test_library_2; GN uses ../../dylibs.
        # TODO(https://fxbug.dev/570694755): Propagate CcInfo from fx_cc_shared_library.
        # @bazel2gn:skip
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_2:test_library_2_lib",
        # In Bazel, fx_cc_library provides headers for test_library_3; GN uses ../../dylibs.
        # TODO(https://fxbug.dev/570694755): Propagate CcInfo from fx_cc_shared_library.
        # @bazel2gn:skip
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_3:lib",
        # In Bazel, fx_cc_library provides headers for test_library_4; GN uses ../../dylibs.
        # TODO(https://fxbug.dev/570694755): Propagate CcInfo from fx_cc_shared_library.
        # @bazel2gn:skip
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_4:lib",
        # In Bazel, fx_cc_library provides headers for test_library_5; GN uses ../../dylibs.
        # TODO(https://fxbug.dev/570694755): Propagate CcInfo from fx_cc_shared_library.
        # @bazel2gn:skip
        "//src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_5:test_library_5_lib",
    ],
)

fx_packaged_binary(
    name = "test_component_${N}_packaged_bin",
    testonly = True,
    binary = ":test_component_${N}_bin",
    binary_name = "test_component_${N}",
)

fx_component_manifest(
    name = "test_component_${N}_manifest",
    testonly = True,
    component_name = "test_component_${N}",
    includes = ["//sdk/lib/syslog:client.shard"],
    manifest = "meta/test_component_${N}.cml",
)

fx_component(
    name = "test_component_${N}_component",
    testonly = True,
    compiled_manifest = ":test_component_${N}_manifest",
    deps = [":test_component_${N}_packaged_bin"],
)

fx_package(
    name = "test_component_${N}_package",
    testonly = True,
    components = [":test_component_${N}_component"],
)
EOL

  # Generate the hand-written part of BUILD.gn. The targets below the bazel2gn
  # sentinel are generated from BUILD.bazel by `fx bazel2gn` below.
  cat <<EOL > "$DIR/BUILD.gn"
# Copyright 2024 The Fuchsia Authors. All rights reserved.
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

# Generated by $0

import("//build/components.gni")

fuchsia_package("test_component_${N}_package") {
  deps = [ ":test_component_${N}_component" ]
  testonly = true
}

group("test_component_${N}") {
  deps = [ ":test_component_${N}_package" ]
  testonly = true
}

## BAZEL2GN SENTINEL - DO NOT EDIT BELOW THIS LINE ##
EOL

  # Generate main.cc
  cat <<EOL > "$DIR/main.cc"
// Copyright 2024 The Fuchsia Authors. All rights reserved.
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Generated by $0

#include <fidl/fidl.examples.routing.echo/cpp/wire.h>
#include <lib/component/incoming/cpp/protocol.h>
#include <unistd.h>

#include "src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_1/lib.h"
#include "src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_2/lib.h"
#include "src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_3/lib.h"
#include "src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_4/lib.h"
#include "src/sys/component_manager/tests/bootfs_launching_benchmark/test_data/dylibs/test_library_5/lib.h"

template <typename T1, typename T2>
void AssertEq(const T1& a, const T2& b) {
  if (a != b) {
    abort();
  }
}

int main() {
  fidl::ClientEnd client_end = component::Connect<fidl_examples_routing_echo::Echo>().value();
  fidl::WireResult result = fidl::WireCall(client_end)->EchoString("${N}");
  AssertEq(result.value().response.get(), "${N}");
  AssertEq(test_library_1_func(), 1);
  AssertEq(test_library_2_func(), 2);
  AssertEq(test_library_3_func(), 3);
  AssertEq(test_library_4_func(), 4);
  AssertEq(test_library_5_func(), 5);
  return EXIT_SUCCESS;
}

EOL

  # Generate cml
  mkdir -p "$DIR/meta"
  cat <<EOL > "$DIR/meta/test_component_${N}.cml"
// Copyright 2024 The Fuchsia Authors. All rights reserved.
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Generated by $0

{
    include: [ "syslog/client.shard.cml" ],
    program: {
        runner: "elf",
        binary: "bin/test_component_${N}",
    },
    use: [
        { protocol: "fidl.examples.routing.echo.Echo" },
    ],
}

EOL

  fx bazel2gn -d "$SCRIPT_DIR/$DIR"
  fx format-code --files="$DIR/BUILD.bazel,$DIR/BUILD.gn,$DIR/main.cc,$DIR/meta/test_component_${N}.cml"
done
