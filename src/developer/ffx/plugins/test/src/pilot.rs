use anyhow::{Context, Result, anyhow};
use serde::Deserialize;
use std::collections::HashMap;
use std::fs;
use std::io::BufReader;
use std::path::Path;
use std::time::Duration;
use test_pilot_lib::test_output::{
    OutputDirectory, TestCaseResult, TestResult, TestStatus, TestTag,
};

const OLD_RUN_SUMMARY_FILE_NAME: &str = "run_summary.json";
const TEST_CASE_RESULT_FORMAT: &str = "FTF";
const TEST_OUTCOME_TAG_KEY: &str = "test_outcome";

/// Converts an output directory generated by run_test_suite_lib into a form compatible with
/// test_pilot.
pub fn convert_output_for_test_pilot(
    output_directory: &Path,
    setup_succeeded: Option<bool>,
    teardown_succeeded: Option<bool>,
) -> Result<()> {
    let output_dir_str = output_directory.to_string_lossy().to_string();
    let output_directory = OutputDirectory::new(output_directory);

    let run_summary_path = output_directory.join(OLD_RUN_SUMMARY_FILE_NAME);

    let file = fs::File::open(&run_summary_path)
        .with_context(|| format!("opening run summary file {run_summary_path:?}"))?;
    let mut reader = BufReader::new(file);
    let run_summary_envelope: RunSummaryEnvelope = serde_json::from_reader(&mut reader)
        .with_context(|| format!("reading run summary file {run_summary_path:?}"))?;

    let run_summary = &run_summary_envelope.data;

    // We only support one suite per test run.
    if run_summary.suites.len() != 1 {
        return Err(anyhow!(
            "{0} contains {1} suite runs, expected 1",
            OLD_RUN_SUMMARY_FILE_NAME,
            run_summary.suites.len(),
        ));
    }

    let suite = &run_summary.suites[0];

    let mut new_summary = TestResult {
        output_dir: output_dir_str.clone(),
        setup_succeeded,
        teardown_succeeded,
        ..Default::default()
    };

    // Create the test directory.
    let new_test_dir_path = output_directory.test_subdir();
    fs::create_dir_all(new_test_dir_path.clone())
        .with_context(|| format!("creating test output subdirectory {new_test_dir_path:?}"))?;

    // Handle suite artifacts.
    let new_test_dir_rel_path = output_directory
        .make_relative(&new_test_dir_path)
        .expect("test dir path is in output_directory");

    if suite.entity_common.artifact_dir.is_empty() {
        if !suite.entity_common.artifacts.is_empty() {
            return Err(anyhow!("suite has artifacts but no artifact directory"));
        }
    } else {
        let old_artifact_dir_path =
            output_directory.join(suite.entity_common.artifact_dir.as_str());

        for name in suite.entity_common.artifacts.keys() {
            let mut new_file_rel_path = new_test_dir_rel_path.to_path_buf();
            new_file_rel_path.push(name);

            new_summary.output_files.push(new_file_rel_path.to_string_lossy().to_string());

            // Move the artifact to <root>/test.
            let mut old_file_path = old_artifact_dir_path.clone();
            old_file_path.push(name);

            let mut new_file_path = new_test_dir_path.clone();
            new_file_path.push(name);

            fs::rename(&old_file_path, &new_file_path).with_context(|| {
                format!("renaming artifact file {old_file_path:?} to {new_file_path:?}")
            })?;
        }

        if old_artifact_dir_path.exists() {
            fs::remove_dir_all(&old_artifact_dir_path)
                .with_context(|| format!("removing directory {old_artifact_dir_path:?}"))?;
        }
    }

    // Handle the cases.
    for old_case in &suite.cases {
        let mut case = TestCaseResult {
            display_name: old_case.name.clone(),
            suite_name: String::new(),
            case_name: old_case.name.clone(),
            status: test_status_from(&old_case.entity_common.outcome),
            duration: Duration::from_millis(
                old_case.entity_common.duration_milliseconds.max(0) as u64
            ),
            format: String::from(TEST_CASE_RESULT_FORMAT),
            failure_reason: None,
            output_files: Vec::new(),
            output_dir: output_dir_str.clone(),
            tags: vec![TestTag {
                key: String::from(TEST_OUTCOME_TAG_KEY),
                value: old_case.entity_common.outcome.clone(),
            }],
        };

        if old_case.entity_common.artifact_dir.is_empty() {
            if !old_case.entity_common.artifacts.is_empty() {
                return Err(anyhow!(
                    "case {} has artifacts but no artifact directory",
                    old_case.name.as_str()
                ));
            }
        } else {
            let old_artifact_dir_path =
                output_directory.join(old_case.entity_common.artifact_dir.as_str());

            let mut escaped_case_name = old_case.name.as_str().replace(['/', '*'], "_");

            let mut new_artifact_dir_path = new_test_dir_path.clone();
            new_artifact_dir_path.push(escaped_case_name.as_str());

            if !old_case.entity_common.artifacts.is_empty() {
                if new_artifact_dir_path.exists() {
                    // The case name is a duplicate in the same test. Add a suffix
                    // (e.g. "_2") to avoid using a duplicate directory name.
                    let mut counter = 1;
                    loop {
                        counter += 1;
                        let new_name = format!("{escaped_case_name}_{counter}");
                        new_artifact_dir_path = new_test_dir_path.clone();
                        new_artifact_dir_path.push(new_name.as_str());
                        if !new_artifact_dir_path.exists() {
                            escaped_case_name = new_name;
                            break;
                        }
                    }
                }
                // Create the new artifact dir at <root>/test/<case name>.
                fs::create_dir(new_artifact_dir_path.clone()).with_context(|| {
                    format!("creating case directory {new_artifact_dir_path:?}")
                })?;
            }

            for name in old_case.entity_common.artifacts.keys() {
                let mut new_file_rel_path = new_test_dir_rel_path.clone();
                new_file_rel_path.push(escaped_case_name.as_str());
                new_file_rel_path.push(name);

                case.output_files.push(new_file_rel_path.to_string_lossy().to_string());

                // Move the artifact to <root>/test/<case name>.
                let mut old_file_path = old_artifact_dir_path.clone();
                old_file_path.push(name);

                let mut new_file_path = new_artifact_dir_path.clone();
                new_file_path.push(name);

                fs::rename(&old_file_path, &new_file_path).with_context(|| {
                    format!("renaming artifact file {old_file_path:?} to {new_file_path:?}")
                })?;
            }

            if old_artifact_dir_path.exists() {
                fs::remove_dir_all(&old_artifact_dir_path).with_context(|| {
                    format!("removing old artifact directory {old_artifact_dir_path:?}")
                })?;
            }
        }

        new_summary.cases.push(case);
    }

    let test_summary_path = output_directory.test_summary();
    fs::write(
        test_summary_path.to_str().unwrap(),
        serde_json::to_string_pretty(&new_summary).unwrap(),
    )
    .with_context(|| {
        format!("writing new summmary file {:?}", test_summary_path.to_str().unwrap())
    })?;

    fs::remove_file(&run_summary_path)
        .with_context(|| format!("removing old summmary file {run_summary_path:?}"))?;

    Ok(())
}

fn test_status_from(old_result: &str) -> TestStatus {
    match old_result {
        "SKIPPED" => TestStatus::Skip,
        "PASSED" | "FINISHED" => TestStatus::Pass,
        "FAILED" => TestStatus::Fail,
        "TIMED_OUT" | "DID_NOT_FINISH" | "STOPPED" => TestStatus::Abort,
        "ERROR" | "INTERNAL_ERROR" => TestStatus::InfraFail,
        _ => {
            eprintln!("UNRECOGNIZED LEGACY RESULT {}", old_result);
            TestStatus::InfraFail
        }
    }
}

/// Top level of the legacy run_summary.json. Identifies the schema.
#[derive(Deserialize, Debug, Default)]
struct RunSummaryEnvelope {
    data: RunSummary,

    #[serde(rename = "schema_id")]
    _schema_id: String,
}

/// The body of the summary. The `entity_common` bit refers to the run.
#[derive(Deserialize, Debug, Default)]
struct RunSummary {
    #[serde(flatten)]
    #[serde(rename = "entity_common")]
    _entity_common: RunSummaryEntityCommon,

    suites: Vec<RunSummarySuiteEntry>,
}

/// Properties of the run, a suite, and a case.
#[derive(Deserialize, Debug, Default)]
struct RunSummaryEntityCommon {
    #[serde(default)]
    artifacts: HashMap<String, RunSummaryArtifactMetadata>,

    #[serde(default)]
    artifact_dir: String,

    #[serde(default)]
    duration_milliseconds: i64,

    // This is the name actually used in summary files, as opposed to the name in the schema, which
    // is start_time_milliseconds.
    #[serde(default)]
    #[serde(rename = "start_time")]
    _start_time: i64,

    outcome: String,
}

/// Describes an artifact.
#[derive(Deserialize, Debug, Default)]
struct RunSummaryArtifactMetadata {
    #[serde(rename = "artifact_type")]
    _artifact_type: String,

    #[serde(default)]
    #[serde(rename = "component_moniker")]
    _component_moniker: String,
}

/// Describes a case.
#[derive(Deserialize, Debug, Default)]
struct RunSummaryCaseEntry {
    #[serde(flatten)]
    entity_common: RunSummaryEntityCommon,

    name: String,
}

/// Describes a suite.
#[derive(Deserialize, Debug, Default)]
struct RunSummarySuiteEntry {
    #[serde(flatten)]
    entity_common: RunSummaryEntityCommon,

    cases: Vec<RunSummaryCaseEntry>,

    #[serde(rename = "name")]
    _name: String,
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    use std::fs;
    use tempfile::tempdir;

    #[test]
    fn test_convert_output() {
        // Setup
        let tmp_dir = tempdir().unwrap();
        let output_dir = tmp_dir.path();

        // Create old run_summary.json
        let run_summary_content = json!({
            "schema_id": "schema_id_string",
            "data": {
                "outcome": "FAILED",
                "suites": [
                    {
                        "name": "suite_name",
                        "outcome": "FAILED",
                        "duration_milliseconds": 123,
                        "artifact_dir": "suite_artifacts",
                        "artifacts": {
                            "stdout.txt": {
                                "artifact_type": "stdout"
                            }
                        },
                        "cases": [
                            {
                                "name": "case1",
                                "outcome": "PASSED",
                                "duration_milliseconds": 100,
                                "artifact_dir": "case1_artifacts",
                                "artifacts": {
                                    "screenshot.png": {
                                        "artifact_type": "screenshot"
                                    }
                                }
                            },
                            {
                                "name": "case2",
                                "outcome": "FAILED",
                                "duration_milliseconds": 23,
                                "artifacts": {},
                                "artifact_dir": "case2_artifacts"
                            }
                        ]
                    }
                ]
            }
        });

        let run_summary_path = output_dir.join(OLD_RUN_SUMMARY_FILE_NAME);
        fs::write(&run_summary_path, serde_json::to_string(&run_summary_content).unwrap()).unwrap();

        // Create artifact directories and files
        let suite_artifact_dir = output_dir.join("suite_artifacts");
        fs::create_dir(&suite_artifact_dir).unwrap();
        fs::write(suite_artifact_dir.join("stdout.txt"), "suite stdout").unwrap();

        let case1_artifact_dir = output_dir.join("case1_artifacts");
        fs::create_dir(&case1_artifact_dir).unwrap();
        fs::write(case1_artifact_dir.join("screenshot.png"), "fake png").unwrap();

        let case2_artifact_dir = output_dir.join("case2_artifacts");
        fs::create_dir(&case2_artifact_dir).unwrap();

        // Run conversion
        let result = convert_output_for_test_pilot(output_dir, Some(true), Some(false));
        assert!(result.is_ok());

        // Assertions
        // 1. old run_summary.json is gone
        assert!(!run_summary_path.exists());

        // 2. new summary.json exists and is correct
        let new_summary_path = output_dir.join("test/output_summary.json");
        assert!(new_summary_path.exists());

        let new_summary_content = fs::read_to_string(&new_summary_path).unwrap();
        let new_summary: TestResult = serde_json::from_str(&new_summary_content).unwrap();

        let expected_output_dir = output_dir.to_string_lossy().to_string();
        assert_eq!(new_summary.output_dir, expected_output_dir);
        assert_eq!(new_summary.setup_succeeded, Some(true));
        assert_eq!(new_summary.teardown_succeeded, Some(false));
        assert_eq!(new_summary.output_files, vec![String::from("test/stdout.txt")]);

        assert_eq!(new_summary.cases.len(), 2);

        let case1 = &new_summary.cases[0];
        assert_eq!(case1.display_name, "case1");
        assert_eq!(case1.suite_name, "");
        assert_eq!(case1.case_name, "case1");
        assert_eq!(case1.duration, Duration::from_millis(100));
        assert_eq!(case1.status, TestStatus::Pass);
        assert_eq!(case1.format, "FTF");
        assert_eq!(case1.output_files, vec![String::from("test/case1/screenshot.png")]);
        assert_eq!(case1.output_dir, expected_output_dir);
        assert_eq!(
            case1.tags,
            vec![TestTag { key: String::from("test_outcome"), value: String::from("PASSED") }]
        );

        let case2 = &new_summary.cases[1];
        assert_eq!(case2.display_name, "case2");
        assert_eq!(case2.suite_name, "");
        assert_eq!(case2.case_name, "case2");
        assert_eq!(case2.duration, Duration::from_millis(23));
        assert_eq!(case2.status, TestStatus::Fail);
        assert_eq!(case2.format, "FTF");
        assert!(case2.output_files.is_empty());
        assert_eq!(case2.output_dir, expected_output_dir);
        assert_eq!(
            case2.tags,
            vec![TestTag { key: String::from("test_outcome"), value: String::from("FAILED") }]
        );

        // 3. artifacts are moved
        let new_suite_artifact_path = output_dir.join("test/stdout.txt");
        assert!(new_suite_artifact_path.exists());
        assert_eq!(fs::read_to_string(new_suite_artifact_path).unwrap(), "suite stdout");

        let new_case1_artifact_path = output_dir.join("test/case1/screenshot.png");
        assert!(new_case1_artifact_path.exists());
        assert_eq!(fs::read_to_string(new_case1_artifact_path).unwrap(), "fake png");

        // 4. old artifact directories are gone
        assert!(!suite_artifact_dir.exists());
        assert!(!case1_artifact_dir.exists());
        assert!(!case2_artifact_dir.exists()); // This one was empty, should be removed.
    }

    #[test]
    fn test_convert_no_cases_no_suite_artifacts() {
        let tmp_dir = tempdir().unwrap();
        let output_dir = tmp_dir.path();

        let run_summary_content = json!({
            "schema_id": "schema_id_string",
            "data": {
                "outcome": "PASSED",
                "suites": [
                    {
                        "name": "suite_name",
                        "outcome": "PASSED",
                        "duration_milliseconds": 42,
                        "cases": []
                    }
                ]
            }
        });

        let run_summary_path = output_dir.join(OLD_RUN_SUMMARY_FILE_NAME);
        fs::write(&run_summary_path, serde_json::to_string(&run_summary_content).unwrap()).unwrap();

        let result = convert_output_for_test_pilot(output_dir, None, None);
        assert!(result.is_ok());

        assert!(!run_summary_path.exists());

        let new_summary_path = output_dir.join("test/output_summary.json");
        assert!(new_summary_path.exists());

        let new_summary: TestResult =
            serde_json::from_str(&fs::read_to_string(new_summary_path).unwrap()).unwrap();

        assert_eq!(new_summary.output_dir, output_dir.to_string_lossy().to_string());
        assert_eq!(new_summary.setup_succeeded, None);
        assert_eq!(new_summary.teardown_succeeded, None);
        assert!(new_summary.output_files.is_empty());
        assert!(new_summary.cases.is_empty());

        assert!(output_dir.exists());
    }

    #[test]
    fn test_convert_multiple_suites_is_error() {
        let tmp_dir = tempdir().unwrap();
        let output_dir = tmp_dir.path();

        let run_summary_content = json!({
            "schema_id": "schema_id_string",
            "data": {
                "outcome": "PASSED",
                "suites": [
                    { "name": "suite1", "outcome": "PASSED", "cases": [] },
                    { "name": "suite2", "outcome": "PASSED", "cases": [] }
                ]
            }
        });

        let run_summary_path = output_dir.join(OLD_RUN_SUMMARY_FILE_NAME);
        fs::write(&run_summary_path, serde_json::to_string(&run_summary_content).unwrap()).unwrap();

        let result = convert_output_for_test_pilot(output_dir, None, None);
        assert!(result.is_err());
        assert_eq!(
            result.unwrap_err().to_string(),
            format!("{0} contains 2 suite runs, expected 1", OLD_RUN_SUMMARY_FILE_NAME)
        );
    }

    #[test]
    fn test_status_from_legacy_result() {
        assert_eq!(test_status_from("SKIPPED"), TestStatus::Skip);
        assert_eq!(test_status_from("PASSED"), TestStatus::Pass);
        assert_eq!(test_status_from("FAILED"), TestStatus::Fail);
        assert_eq!(test_status_from("TIMED_OUT"), TestStatus::Abort);
        assert_eq!(test_status_from("ERROR"), TestStatus::InfraFail);
        assert_eq!(test_status_from("FINISHED"), TestStatus::Pass);
        assert_eq!(test_status_from("DID_NOT_FINISH"), TestStatus::Abort);
        assert_eq!(test_status_from("STOPPED"), TestStatus::Abort);
        assert_eq!(test_status_from("INTERNAL_ERROR"), TestStatus::InfraFail);
        assert_eq!(test_status_from("UNRECOGNIZED"), TestStatus::InfraFail);
    }
}
