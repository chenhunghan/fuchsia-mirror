#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DataWidth {
    U8,
    U16,
    U32,
    U64,
}

/// The different data widths used by eBPF.
impl DataWidth {
    pub fn bits(&self) -> usize {
        match self {
            Self::U8 => 8,
            Self::U16 => 16,
            Self::U32 => 32,
            Self::U64 => 64,
        }
    }

    pub fn bytes(&self) -> usize {
        match self {
            Self::U8 => 1,
            Self::U16 => 2,
            Self::U32 => 4,
            Self::U64 => 8,
        }
    }

    pub fn str(&self) -> &'static str {
        match self {
            Self::U8 => "b",
            Self::U16 => "h",
            Self::U32 => "w",
            Self::U64 => "dw",
        }
    }

    pub fn instruction_bits(&self) -> u8 {
        match self {
            Self::U8 => BPF_B,
            Self::U16 => BPF_H,
            Self::U32 => BPF_W,
            Self::U64 => BPF_DW,
        }
    }
}

/// Applies an eBPF endianness conversion (`BPF_TO_BE` when `to_be` is true,
/// `BPF_TO_LE` when `to_be` is false) on a little-endian target.
#[cfg(target_endian = "little")]
pub fn apply_endianness(to_be: bool, width: DataWidth, value: u64) -> u64 {
    if to_be {
        match width {
            DataWidth::U16 => {
                let v = value & 0xffff;
                ((v & 0x00ff) << 8) | ((v & 0xff00) >> 8)
            }
            DataWidth::U32 => {
                let v = value & 0xffff_ffff;
                ((v & 0x0000_00ff) << 24)
                    | ((v & 0x0000_ff00) << 8)
                    | ((v & 0x00ff_0000) >> 8)
                    | ((v & 0xff00_0000) >> 24)
            }
            DataWidth::U64 => {
                ((value & 0x0000_0000_0000_00ff) << 56)
                    | ((value & 0x0000_0000_0000_ff00) << 40)
                    | ((value & 0x0000_0000_00ff_0000) << 24)
                    | ((value & 0x0000_0000_ff00_0000) << 8)
                    | ((value & 0x0000_00ff_0000_0000) >> 8)
                    | ((value & 0x0000_ff00_0000_0000) >> 24)
                    | ((value & 0x00ff_0000_0000_0000) >> 40)
                    | ((value & 0xff00_0000_0000_0000) >> 56)
            }
            DataWidth::U8 => value & 0xff,
        }
    } else {
        match width {
            DataWidth::U16 => value & 0xffff,
            DataWidth::U32 => value & 0xffff_ffff,
            DataWidth::U64 => value,
            DataWidth::U8 => value & 0xff,
        }
    }
}

