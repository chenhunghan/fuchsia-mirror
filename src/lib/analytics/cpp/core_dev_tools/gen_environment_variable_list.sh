# Converts a file that lists one environment variable name per line into a C++
# include file that lists the names as string literals. Each literal ends with
# a comma, so that the output can be included in an array initializer.
#
# Usage: gen_environment_variable_list.sh <output> <input>

output="$1"
input="$2"

# Blank lines and comments in the input are ignored.
names="$(sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e '/^$/d' -e '/^#/d' "${input}")"

# Keep internal spaces and glob characters intact so the loop can reject them.
set -f
IFS='
'

for name in ${names}; do
  case "${name}" in
    [!A-Za-z_]* | *[!A-Za-z0-9_]*)
      echo "$0: invalid environment variable name in ${input}: ${name}" >&2
      exit 1
      ;;
  esac
done

{
  echo '// DO NOT EDIT THIS FILE'
  echo '// Generated by gen_environment_variable_list.sh'
  for name in ${names}; do
    echo "\"${name}\","
  done
} > "${output}"
