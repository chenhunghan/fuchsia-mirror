# Check per-target TODO on rustc_* `# @bazel2gn:raw_attribute:configs -=` directives
def check_rustc_configs_remove_todo(d, rel, text):
    base_lines = set(l.strip() for l in base_text(rel).splitlines())
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() in base_lines:
            continue
        if not re.search(r"#\s*@bazel2gn:raw_attribute:configs\s*-=", line):
            continue
        k = i + 1
        while k < len(lines) and lines[k].strip().startswith("#"):
            k += 1
        if k >= len(lines) or not re.match(r"^\s*rustc_[a-z_]+\(\s*$", lines[k]):
            continue
        top = i
        while top > 0 and lines[top - 1].strip().startswith("#"):
            top -= 1
        comment_block = "\n".join(lines[top:k])
        if "TODO" in comment_block and "disable_build_flags" in comment_block:
            continue
        _emit(
            findings,
            "rustc_configs_remove_missing_todo",
            "WARNING",
            rel,
            i + 1,
            "`# @bazel2gn:raw_attribute:configs -=` on a `rustc_*` target lacks a "
            "`TODO(https://fxbug.dev/566966051)` referencing `disable_build_flags`.",
            RUSTC_CONFIGS_REMOVE_REMEDIATION,
        )


# Collect candidate plain-text list files referenced in package build files
def collect_local_list_files(d, bazel_src):
    gn_rel = os.path.join(d, "BUILD.gn")
    combined = bazel_src + "\n" + base_text(gn_rel)
    gn_path = os.path.join(workdir, gn_rel)
    if os.path.isfile(gn_path):
        with open(gn_path, encoding="utf-8", errors="replace") as gf:
            combined += "\n" + gf.read()
    candidates = []
    seen = set()
    for fname in re.findall(r'"([A-Za-z0-9_./-]+\.[A-Za-z0-9_.-]+)"', combined):
        if fname in seen or fname.startswith(("/", ":", "@", "$")):
            continue
        if fname.endswith(SKIP_LIST_FILE_EXTS):
            continue
        seen.add(fname)
        fpath = os.path.join(workdir, d, fname)
        if not os.path.isfile(fpath) or os.path.getsize(fpath) > 65536:
            continue
        with open(fpath, encoding="utf-8", errors="replace") as lf:
            raw_entries = [
                ln.split("#", 1)[0].strip() for ln in lf.read().splitlines()
            ]
        entries = [
            e
            for e in raw_entries
            if e and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.$@:-]*", e)
        ]
        if 2 <= len(entries) <= 200:
            candidates.append((fname, entries))
    return candidates


# Check hardcoded Starlark list attributes derived from a local list/allowlist file
def check_inlined_file_lists(d, rel, text):
    list_files = collect_local_list_files(d, text)
    if not list_files:
        return
    lines = text.splitlines()
    for m in re.finditer(
        r"^[ \t]+([a-z_][a-z0-9_]*)\s*=\s*\[(.*?)\]", text, re.M | re.S
    ):
        attr = m.group(1)
        if attr in NON_FLAG_LIST_ATTRS:
            continue
        items = re.findall(r'"([^"]+)"', m.group(2))
        if len(items) < 2:
            continue
        start_idx = text[: m.start()].count("\n")
        end_idx = text[: m.end()].count("\n")
        window = "\n".join(
            lines[max(0, start_idx - 5) : min(len(lines), end_idx + 5)]
        )
        for fname, entries in list_files:
            matched = sum(1 for sym in entries if any(sym in it for it in items))
            if matched < max(2, (len(entries) + 1) // 2):
                continue
            has_if = bool(re.search(r"#\s*LINT\.IfChange\b", window))
            has_then = bool(
                re.search(
                    r"#\s*LINT\.ThenChange\([^)]*"
                    + re.escape(os.path.basename(fname))
                    + r"[^)]*\)",
                    window,
                )
            )
            if has_if and has_then:
                continue
            _emit(
                findings,
                "inlined_file_list_missing_ifttt",
                "WARNING",
                rel,
                start_idx + 1,
                f"`{attr} = [...]` hardcodes entries from `{fname}` without a "
                f"`# LINT.IfChange` / `# LINT.ThenChange({fname})` pair to keep "
                "both copies in sync.",
                INLINED_LIST_IFTTT_REMEDIATION,
            )


# Find the nearest enclosing Bazel package directory for an in-tree include path
def find_enclosing_bazel_pkg(inc):
    cur = os.path.dirname(inc)
    while cur:
        if os.path.isfile(os.path.join(workdir, cur, "BUILD.bazel")):
            return cur
        parent = os.path.dirname(cur)
        if parent == cur:
            break
        cur = parent
    return ""


# Build remediation for an upstream BUILD.bazel header mismatch without leaking unowned GN headers.
def _build_upstream_header_remediation(inc_pkg, up_bz_rel, rel_hdr, base_gn_omits_hdr):
    up_gn_rel = f"{inc_pkg}/BUILD.gn"
    if base_gn_omits_hdr:
        return (
            f"Reset any broad rule or visibility rewrites in `{up_bz_rel}` and `{up_gn_rel}` "
            f"(`git checkout HEAD~1 -- {up_bz_rel} {up_gn_rel}`), keep all pre-existing "
            f"rules and `default_visibility` unchanged in `{up_bz_rel}`, and add only a "
            f"documented `# @bazel2gn:skip` entry inside `hdrs = [...]` of the owning C/C++ "
            f"library target in `{up_bz_rel}`:\n"
            "  # Exposed in Bazel sandbox; omitted from GN public headers.\n"
            f'  "{rel_hdr}",  # @bazel2gn:skip\n'
            f"Leave `{up_gn_rel}` untouched (adding `{rel_hdr}` to GN `public` triggers "
            "`gn check` failures in unrelated targets that include it transitively) and "
            f"verify `fx bazel2gn --check -d {inc_pkg}` passes."
        )
    return (
        f"Make a minimal, surgical edit in `{up_bz_rel}` adding `\"{rel_hdr}\"` to `hdrs` "
        "of the owning C/C++ library target (preserving all pre-existing rule macros and "
        f"`default_visibility` unchanged), then run `fx bazel2gn -d {inc_pkg}` if "
        f"`{up_gn_rel}` contains `BAZEL2GN SENTINEL`."
    )


# Check #included headers omitted from hdrs (or leaked into GN public) in upstream packages.
def check_undeclared_upstream_cc_headers(d, rel, text):
    cc_call_re = re.compile(
        r"^((?:fx_cc_|cc_|idk_cc_)[a-z0-9_]*)\(\s*$", re.M
    )
    inc_re = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)
    target_set = set(target_dirs)
    reported = set()
    pkg_cache = {}

    for m in cc_call_re.finditer(text):
        block = block_at(text, m.end() - 1)
        dep_labels = list_attr(block, "deps") + list_attr(block, "implementation_deps")
        dep_pkgs = {
            lab.lstrip("@").split(":", 1)[0].strip("/")
            for lab in dep_labels
            if not lab.startswith(":")
        }
        if not dep_pkgs:
            continue

        all_includes = set()
        for src_or_hdr in list_attr(block, "srcs") + list_attr(block, "hdrs"):
            if src_or_hdr.startswith((":", "//", "@")):
                continue
            fpath = os.path.join(workdir, d, src_or_hdr)
            if not os.path.isfile(fpath):
                continue
            with open(fpath, encoding="utf-8", errors="replace") as sf:
                all_includes.update(inc_re.findall(sf.read()))

        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        tname = name_m.group(1) if name_m else "?"
        line = text[: m.start()].count("\n") + 1

        for inc in sorted(all_includes):
            if "/" not in inc or not os.path.isfile(os.path.join(workdir, inc)):
                continue
            inc_pkg = find_enclosing_bazel_pkg(inc)
            if not inc_pkg or inc_pkg in target_set or inc_pkg not in dep_pkgs:
                continue
            if inc_pkg.startswith(("third_party/", "prebuilt/", "out/", "build/")):
                continue
            rel_hdr = os.path.relpath(
                os.path.join(workdir, inc), os.path.join(workdir, inc_pkg)
            ).replace(os.sep, "/")
            up_bz_rel = f"{inc_pkg}/BUILD.bazel"
            up_gn_rel = f"{inc_pkg}/BUILD.gn"
            if up_bz_rel not in pkg_cache:
                with open(
                    os.path.join(workdir, up_bz_rel), encoding="utf-8", errors="replace"
                ) as uf:
                    cur_bz = uf.read()
                cur_gn = ""
                if os.path.isfile(os.path.join(workdir, up_gn_rel)):
                    with open(
                        os.path.join(workdir, up_gn_rel), encoding="utf-8", errors="replace"
                    ) as gf:
                        cur_gn = gf.read()
                pkg_cache[up_bz_rel] = (cur_bz, cur_gn, base_text(up_gn_rel))
            up_bz_text, up_gn_text, base_gn_text = pkg_cache[up_bz_rel]
            if "glob(" in up_bz_text:
                continue
            has_sentinel = "BAZEL2GN SENTINEL" in up_gn_text
            base_gn_omits_hdr = has_sentinel and (
                f'"{rel_hdr}"' not in (base_gn_text or up_gn_text)
            )
            leaked_into_gn = (
                base_gn_omits_hdr
                and f'"{rel_hdr}"' in up_gn_text
                and f'"{rel_hdr}"' in up_bz_text
            )
            missing_in_bz = f'"{rel_hdr}"' not in up_bz_text
            if not missing_in_bz and not leaked_into_gn:
                continue
            key = (rel, inc_pkg, rel_hdr)
            if key in reported:
                continue
            reported.add(key)
            if leaked_into_gn:
                msg = (
                    f'{m.group(1)}(name = "{tname}") includes "{inc}" under dual-build '
                    f'dependency "//{inc_pkg}", where "{rel_hdr}" was added to `hdrs` '
                    f"in `{up_bz_rel}` without `# @bazel2gn:skip` and synced into "
                    f"`{up_gn_rel}`, breaking `gn check` in unrelated targets because "
                    f"`{up_gn_rel}` previously left `{rel_hdr}` unowned."
                )
            else:
                msg = (
                    f'{m.group(1)}(name = "{tname}") includes "{inc}", which exists on disk '
                    f'under already-migrated dependency "//{inc_pkg}" as "{rel_hdr}", but '
                    f'"{rel_hdr}" is omitted from hdrs in {up_bz_rel} (causing Bazel sandbox '
                    f"compile failure: fatal error: '{inc}' file not found)."
                )
            rem = _build_upstream_header_remediation(
                inc_pkg, up_bz_rel, rel_hdr, base_gn_omits_hdr
            )
            _emit(
                findings,
                "undeclared_upstream_cc_header",
                "ERROR",
                rel,
                line,
                msg,
                rem,
            )


