# Review-driven checks on the BUILD.bazel files of the target directories:
#
# 1. undocumented_bazel2gn_directive: every `# @bazel2gn:` directive (skip,
#    raw_attribute, raw_overwrite, value_overwrite, path_overwrite) that the
#    change adds needs a short human comment explaining why Bazel and GN differ.
#    One comment may cover a stacked group of directives, and one documented
#    directive covers identical directives elsewhere in the same file.
#
# 2. public_header_dep_in_implementation_deps: a C/C++ library whose public
#    headers (hdrs) #include a dependency's headers must list that dependency in
#    `deps` (GN public_deps), not `implementation_deps` (GN deps).
#
# 3. rustc_configs_remove_missing_todo: every `# @bazel2gn:raw_attribute:configs -=`
#    directive on a `rustc_*` rule must include a `TODO(https://fxbug.dev/566966051)`
#    comment noting the future migration to `disable_build_flags`.
#
# 4. inlined_file_list_missing_ifttt: when a list attribute (such as
#    `linkopts`) hardcodes entries from a local allowlist/symbol file that GN or
#    a genrule reads from disk, the list must be guarded with `# LINT.IfChange`
#    and `# LINT.ThenChange(<file>)` so the two copies cannot silently drift.
#
# 5. undeclared_upstream_cc_header: when a migrated C/C++ target #includes an
#    existing in-tree header whose enclosing already-migrated BUILD.bazel omits
#    that relative header path from `hdrs` (or adds it without `# @bazel2gn:skip`
#    when the upstream BUILD.gn omits that header), flags the upstream mismatch
#    with surgical `hdrs` remediation that preserves `gn check` and BUILD.gn sync.
#
# 6. dropped_gn_comment_block: when migrating a package from BUILD.gn to
#    BUILD.bazel, multi-line explanatory comment blocks removed from BUILD.gn
#    must be preserved in BUILD.bazel (rather than dropped or collapsed into a
#    brief paraphrase) and placed directly above the migrated attribute when the
#    original comment documented a specific GN list attribute (e.g. test_deps).
#
# 7. redundant_builtin_label_directive: a new `# @bazel2gn:` directive that
#    overrides an external Bazel repository label which bazel2gn already maps
#    to a GN label via its built-in third-party label map is unnecessary.
#
# 8. stale_gn_retention_comment_in_bazel / gn_template_generated_comment_in_bazel:
#    a comment block in BUILD.bazel placed above a Bazel target that describes
#    the target as retained/staying in GN (e.g. "Retained in GN because..."),
#    or a header comment in BUILD.bazel claiming the file was generated by a
#    `BUILD.gn.tmpl` / `fx create` GN scaffolding template, is contradictory
#    in BUILD.bazel.
#
# 9. copts_default_include_dirs: `copts = ["-I."]` on fx_cc_* targets that is
#    unneeded (no angled workspace-root include) or lacks an explanatory comment.
#    (`# @bazel2gn:raw_attribute:output_name` on fx_cc_binary / fx_cc_test_binary /
#    fx_cc_test / rustc_test targets is reported by bazel_minimality
#    cc_binary_raw_output_name_annotation / rustc_test_raw_output_name_annotation.)
#
# A new directive that check 7, bazel_minimality (raw_attribute:output_name) or
# migration_sanity (redundant_bazel2gn_skip on a noGNEquivalent rule) asks to
# remove is not also flagged by check 1.

