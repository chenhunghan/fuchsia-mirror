# Find the 1-based line number of a stale GN-retention or dual-build sync comment
# on a BUILD.bazel target, or None when the comment block is valid.
def _find_stale_bazel_target_comment(
    start, raw, has_skip, has_dual_build_sentinel
):
    prose_lines = [
        (offset, ln.lstrip("#").strip())
        for offset, ln in enumerate(raw)
        if not DIRECTIVE_RE.search(ln) and ln.lstrip("#").strip()
    ]
    if not prose_lines:
        return None
    joined_prose = " ".join(body for _, body in prose_lines)
    for offset, body in prose_lines:
        if GN_RETENTION_COMMENT_RE.search(body):
            return start + offset + 1, "retention"
    if BAZEL_EQUIV_SELF_REF_RE.search(joined_prose):
        return start + prose_lines[0][0] + 1, "dual_build"
    if not (has_skip and has_dual_build_sentinel) and (
        PRE_SENTINEL_GN_TARGET_REF_RE.search(joined_prose)
    ):
        return start + prose_lines[0][0] + 1, "dual_build"
    return None


# Check for stale GN-retention or dual-build sync comments on targets in BUILD.bazel.
def check_stale_gn_retention_comments(d, rel, text):
    base_src = base_text(rel)
    base_blocks = {
        "\n".join(ln.strip() for ln in blk[3])
        for blk in _extract_comment_blocks(base_src)
    }
    gn_rel = os.path.join(d, "BUILD.gn")
    gn_path = os.path.join(workdir, gn_rel)
    has_dual_build_sentinel = False
    if os.path.isfile(gn_path):
        try:
            with open(gn_path, encoding="utf-8", errors="replace") as gf:
                has_dual_build_sentinel = "BAZEL2GN SENTINEL" in gf.read()
        except OSError:
            has_dual_build_sentinel = False
    sentinel_removed = (
        "BAZEL2GN SENTINEL" in base_text(gn_rel) and not has_dual_build_sentinel
    )
    for start, end, _, raw, next_idx, next_line in _extract_comment_blocks(text):
        norm_blk = "\n".join(ln.strip() for ln in raw)
        if norm_blk in base_blocks and not sentinel_removed:
            continue
