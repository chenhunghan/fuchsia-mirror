            m.group(1) == "skip"
            for ln in raw
            for m in [DIRECTIVE_RE.search(ln)]
            if m
        )
        stale_hit = _find_stale_bazel_target_comment(
            start, raw, has_skip, has_dual_build_sentinel
        )
