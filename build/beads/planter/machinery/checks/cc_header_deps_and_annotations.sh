# Build a suggested Bazel Starlark attribute comment for a commented-out GN attribute.
def _bazel_commented_attr_hint(gn_attr, op, rhs):
    if gn_attr == "configs":
        q_vals = re.findall(r'"([^"]+)"', rhs)
        if q_vals and "rust/lints" in q_vals[0]:
            return f'`# lint_config = "{q_vals[0]}",`'
        if op == "-=":
            return "`# disable_build_flags = [...],`"
        return '`# build_flags = [...],` (or `# lint_config = "...",` on Rust targets)'
    if gn_attr in ("public_configs", "all_dependent_configs"):
        return "`# build_flags = [...],` (or `# includes = [...],` / `# defines = [...],` / `# copts = [...],`)"
    if gn_attr in (
        "cflags",
        "cflags_c",
        "cflags_cc",
        "cflags_objc",
        "cflags_objcc",
        "asmflags",
    ):
        return "`# copts = [...],`"
    if gn_attr == "rustflags":
        return "`# rustc_flags = [...],`"
    if gn_attr in ("ldflags", "arflags"):
        return "`# linkopts = [...],`"
    if gn_attr == "defines":
        return "`# defines = [...],`"
    if gn_attr == "features":
        return "`# crate_features = [...],`"
    if gn_attr == "include_dirs":
        return "`# includes = [...],`"
    if gn_attr == "rustenv":
        return "`# rustc_env = {...},`"
    return f"`# {gn_attr} = ...,`"


# Check for commented-out GN attribute assignments copied verbatim into Bazel rule calls.
def check_untranslated_gn_commented_attrs(d, rel, text):
    if d == "build/config" or d.startswith("build/config/"):
        return
    non_translatable_list_attrs = {
        "deps",
        "public_deps",
        "test_deps",
        "data_deps",
        "sources",
        "public",
        "inputs",
    }
    base_lines = set(l.strip() for l in base_text(rel).splitlines())
    for cm in re.finditer(r"^([a-z_][a-z0-9_]*)\(\s*$", text, re.M):
        rule_name = cm.group(1)
        if rule_name in ("package", "build_flags", "exports_files", "licenses"):
            continue
        block = block_at(text, cm.end() - 1)
        start_line_idx = text[: cm.start()].count("\n")
        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        tname = name_m.group(1) if name_m else "?"
        b_lines = block.splitlines()
        for offset, ln in enumerate(b_lines):
            s = ln.strip()
            if not s.startswith("#") or s in base_lines or DIRECTIVE_RE.search(s):
                continue
            k = offset + 1
            while (
                k < len(b_lines)
                and b_lines[k].strip().startswith("#")
                and not DIRECTIVE_RE.search(b_lines[k])
            ):
                k += 1
            if k < len(b_lines) and DIRECTIVE_RE.search(b_lines[k]):
                continue
            body = s.lstrip("#").strip()
            m_aug = re.match(
                r"^([a-z_][a-z0-9_]*)\s*(\+=|-=)\s*"
                r'(\[\s*$|\[[^\]]*\](?:\s*,)?|"[^"]*"(?:\s*,)?)$',
                body,
            )
            m_eq = None
            if not m_aug:
                m_eq = re.match(
                    r"^(configs|public_configs|all_dependent_configs|cflags|cflags_c|"
                    r"cflags_cc|cflags_objc|cflags_objcc|rustflags|ldflags|arflags|"
                    r"asmflags|include_dirs|rustenv)\s*(=)\s*"
                    r'(\[\s*$|\[[^\]]*\](?:\s*,)?|"[^"]*"(?:\s*,)?)$',
                    body,
                )
            m_hit = m_aug or m_eq
            if not m_hit:
                continue
            gn_attr, op, rhs = m_hit.groups()
            if gn_attr in non_translatable_list_attrs:
                rem = (
                    f'Remove dead commented-out GN `{gn_attr}` syntax (`{s}`) from '
                    f'`{rule_name}(name = "{tname}")` in `{rel}` (preserving any '
                    "accompanying `# TODO(...)` or prose rationale comment if applicable; "
                    "commented-out dependency/source lists are not carried over to "
                    "`BUILD.bazel`). Once all deterministic checks pass, dispute any "
                    "resulting `review_diff/dropped_comment` false positive in "
                    "`CoderReport.disputed_findings`."
                )
            else:
                hint = _bazel_commented_attr_hint(gn_attr, op, rhs)
                rem = (
                    f'Translate `{s}` on `{rule_name}(name = "{tname}")` in `{rel}` to '
                    f"its commented-out Bazel Starlark equivalent (such as {hint}) so "
                    "uncommenting it during local development remains valid Starlark "
                    "(or remove it if it was an undocumented dead comment). Once all "
                    "deterministic checks pass, dispute any resulting "
                    "`review_diff/dropped_comment` false positive in "
                    "`CoderReport.disputed_findings`."
                )
            _emit(
                findings,
                "untranslated_gn_commented_attr",
                "ERROR",
                rel,
                start_line_idx + offset + 1,
                f'`{rule_name}(name = "{tname}")` in `{rel}` carries raw GN '
                f"commented-out attribute syntax (`{s}`), which is invalid Starlark "
                "if uncommented.",
                rem,
            )


