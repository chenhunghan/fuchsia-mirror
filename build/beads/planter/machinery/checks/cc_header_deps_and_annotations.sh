_CC_CALLER_RULES = _CC_HDR_SYNC_RULES | {
    "cc_source_library_zx",
    "idk_cc_source_library_zx",
    "idk_cc_static_library_zx",
    "cc_binary",
    "fx_cc_binary",
    "cc_test",
    "fx_cc_test",
    "fx_cc_test_binary",
}


# Check whether a concrete Bazel visibility entry list allows `caller_pkg`.
def _vis_entries_cover_pkg(caller_pkg: str, dep_pkg: str, vis_entries) -> bool:
    if not vis_entries:
        return False
    for entry in vis_entries:
        if entry == "//visibility:public":
            return True
        if entry == "//visibility:private":
            if caller_pkg == dep_pkg:
                return True
            continue
        m = re.match(r"^(?://([^:]*))?:__(pkg|subpackages)__$", entry)
        if not m:
            return True
        scope = dep_pkg if m.group(1) is None else m.group(1).strip("/")
        kind = m.group(2)
        if kind == "pkg" and caller_pkg == scope:
            return True
        if kind == "subpackages" and (
            scope == ""
            or caller_pkg == scope
            or caller_pkg.startswith(scope + "/")
        ):
            return True
    return False


# Collect all #include paths across C/C++ sources and headers in package `d`.
def _collect_pkg_cc_includes(d: str) -> set[str]:
    pkg_abs = os.path.join(workdir, d)
    if not os.path.isdir(pkg_abs):
        return set()
    cc_exts = (".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".hh", ".inc")
    inc_re = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)
    includes: set[str] = set()
    for root, _, files in os.walk(pkg_abs):
        for fn in files:
            if not fn.endswith(cc_exts):
                continue
            fpath = os.path.join(root, fn)
            try:
                with open(fpath, encoding="utf-8", errors="replace") as sf:
                    includes.update(inc_re.findall(sf.read()))
            except OSError:
                continue
    return includes


# Parse C/C++ library targets (hdrs, alwayslink, visibility) from a BUILD.bazel string.
def _parse_dep_cc_lib_targets(bz_src: str) -> dict[str, dict]:
    try:
        tree = ast.parse(bz_src)
    except SyntaxError:
        return {}
    pkg_default_vis = None
    raw_targets: dict[str, dict] = {}
    for stmt in tree.body:
        if not (isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call)):
            continue
        call = stmt.value
        fn = call.func.id if isinstance(call.func, ast.Name) else ""
        if fn == "package":
            for kw in call.keywords:
                if kw.arg == "default_visibility" and isinstance(
                    kw.value, ast.List
                ):
                    pkg_default_vis = [
                        e.value
                        for e in kw.value.elts
                        if isinstance(e, ast.Constant)
                        and isinstance(e.value, str)
                    ]
            continue
        if not (
            fn in _CC_CALLER_RULES
            or fn.startswith(("cc_", "fx_cc_", "idk_cc_"))
        ):
            continue
        tname = None
        hdrs: list[str] = []
        vis = None
        alwayslink = False
        local_deps: list[str] = []
        for kw in call.keywords:
            if (
                kw.arg == "name"
                and isinstance(kw.value, ast.Constant)
                and isinstance(kw.value.value, str)
            ):
                tname = kw.value.value
            elif kw.arg == "hdrs":
                hdrs = [
                    sub.value
                    for sub in ast.walk(kw.value)
                    if isinstance(sub, ast.Constant)
                    and isinstance(sub.value, str)
                    and not sub.value.startswith(("//", "@", ":"))
                ]
            elif kw.arg == "visibility" and isinstance(kw.value, ast.List):
                vis = [
                    e.value
                    for e in kw.value.elts
                    if isinstance(e, ast.Constant) and isinstance(e.value, str)
                ]
            elif kw.arg == "alwayslink":
                if isinstance(kw.value, ast.Constant) and kw.value.value is True:
                    alwayslink = True
            elif kw.arg == "deps":
                local_deps = [
                    sub.value[1:]
                    for sub in ast.walk(kw.value)
                    if isinstance(sub, ast.Constant)
                    and isinstance(sub.value, str)
                    and sub.value.startswith(":")
                ]
        if tname:
            raw_targets[tname] = {
                "hdrs": hdrs,
                "vis": vis if vis is not None else pkg_default_vis,
                "alwayslink": alwayslink,
                "local_deps": local_deps,
            }
    for info in raw_targets.values():
        combined_hdrs = list(info["hdrs"])
        for ldep in info["local_deps"]:
            if ldep in raw_targets:
                combined_hdrs.extend(raw_targets[ldep]["hdrs"])
        info["all_hdrs"] = list(dict.fromkeys(combined_hdrs))
    return raw_targets


# Flag unused cross-package C/C++ library deps whose upstream visibility was restricted.
def check_unused_cc_deps_with_restricted_visibility(
    d: str, rel: str, text: str
) -> None:
    try:
        tree = ast.parse(text, filename=rel)
    except SyntaxError:
        return
    pkg_includes = _collect_pkg_cc_includes(d)
    target_set = set(target_dirs)
    dep_cache: dict[str, tuple[dict, dict]] = {}

    for stmt in tree.body:
        if not (isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call)):
            continue
        call = stmt.value
        rule_name = call.func.id if isinstance(call.func, ast.Name) else ""
        if not (
            rule_name in _CC_CALLER_RULES
            or rule_name.startswith(("cc_", "fx_cc_", "idk_cc_"))
        ):
            continue
        tname = None
        for kw in call.keywords:
            if (
                kw.arg == "name"
                and isinstance(kw.value, ast.Constant)
                and isinstance(kw.value.value, str)
            ):
                tname = kw.value.value
                break
        if not tname:
            continue
        for kw in call.keywords:
            if kw.arg not in ("deps", "implementation_deps"):
                continue
            attr_name = kw.arg
            for sub in ast.walk(kw.value):
                if not (
                    isinstance(sub, ast.Constant) and isinstance(sub.value, str)
                ):
                    continue
                lbl = sub.value.strip()
                if not lbl.startswith("//") or lbl.startswith(
                    ("//conditions:", "//visibility:")
                ):
                    continue
                body = lbl[2:]
                if ":" in body:
                    dep_pkg, dep_target = body.split(":", 1)
                else:
                    dep_pkg = body.strip("/")
                    dep_target = os.path.basename(dep_pkg)
                dep_pkg = dep_pkg.strip("/")
                if (
                    not dep_pkg
                    or dep_pkg == d
                    or dep_pkg in target_set
                    or dep_pkg.startswith(
                        ("third_party/", "prebuilt/", "out/", "build/")
                    )
                ):
                    continue
                dep_bz_rel = f"{dep_pkg}/BUILD.bazel"
                dep_bz_abs = os.path.join(workdir, dep_bz_rel)
                if not os.path.isfile(dep_bz_abs):
                    continue
                if dep_bz_rel not in dep_cache:
                    with open(
                        dep_bz_abs, encoding="utf-8", errors="replace"
                    ) as df:
                        cur_src = df.read()
                    b_src = base_text(dep_bz_rel) or cur_src
                    dep_cache[dep_bz_rel] = (
                        _parse_dep_cc_lib_targets(cur_src),
                        _parse_dep_cc_lib_targets(b_src),
                    )
                cur_targets, base_targets = dep_cache[dep_bz_rel]
                cur_info = cur_targets.get(dep_target)
                base_info = base_targets.get(dep_target, cur_info)
                if not cur_info or cur_info["alwayslink"]:
                    continue
                dep_hdrs = cur_info["all_hdrs"]
                if not dep_hdrs:
                    continue
                base_vis = base_info["vis"] if base_info else None
                if _vis_entries_cover_pkg(d, dep_pkg, base_vis):
                    continue
                hdr_used = any(
                    inc == os.path.basename(h)
                    or inc.endswith("/" + os.path.basename(h))
                    for h in dep_hdrs
                    for inc in pkg_includes
                )
                if hdr_used:
                    continue
                cur_covered = _vis_entries_cover_pkg(
                    d, dep_pkg, cur_info["vis"]
                )
                hdrs_desc = ", ".join(f'`"{h}"`' for h in dep_hdrs[:3])
                line_no = getattr(sub, "lineno", getattr(kw, "lineno", 1))
                if cur_covered:
                    msg = (
                        f'`{rule_name}(name = "{tname}")` lists `"{lbl}"` in '
                        f"`{attr_name}`, but no source or header in `{d}` "
                        f"`#include`s any header from `{lbl}` (`hdrs`: "
                        f"{hdrs_desc}), and keeping this unused dependency "
                        f"requires puncturing restricted visibility in "
                        f"`{dep_bz_rel}`."
                    )
                    rem = (
                        f'Remove `"{lbl}"` from `{attr_name}` on `"{tname}"` '
                        f"in `{rel}`, revert the visibility entry added for "
                        f'`"//{d}"` in `{dep_bz_rel}`, and re-run '
                        f"`fx bazel2gn -d {d}`."
                    )
                else:
                    msg = (
                        f'`{rule_name}(name = "{tname}")` lists `"{lbl}"` in '
                        f"`{attr_name}`, which is not visible to `//{d}` in "
                        f"`{dep_bz_rel}`, and no source or header in `{d}` "
                        f"`#include`s any header from `{lbl}` (`hdrs`: "
                        f"{hdrs_desc})."
                    )
                    rem = (
                        f'Remove the unused `"{lbl}"` dependency from '
                        f'`{attr_name}` on `"{tname}"` in `{rel}` (do not '
                        f"widen visibility in `{dep_bz_rel}`) and re-run "
                        f"`fx bazel2gn -d {d}`."
                    )
                _emit(
                    findings,
                    "unused_cc_dep_visibility_puncture",
                    "ERROR",
                    rel,
                    line_no,
                    msg,
                    rem,
                )


