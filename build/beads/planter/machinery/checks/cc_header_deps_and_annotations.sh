        or "bsd-style license" in low
        or "license file" in low
    ):
        return set(), set()
    if any(
        marker in joined
        for marker in (
            "BAZEL2GN SENTINEL",
            "AUTO-GENERATED",
            "Assignment had no effect",
        )
    ):
        return set(), set()
    code_like = sum(
        1
        for b in bodies
        if b.endswith(("{", "}", "[", "]", ","))
        or b.startswith(('"//', '":', "import("))
