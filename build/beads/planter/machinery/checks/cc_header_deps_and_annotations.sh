DIRECTIVE_RE = re.compile(r"#\s*@bazel2gn:([a-z_]+)(:.*)?$")
CC_RULE_RE = re.compile(r"^(fx_cc_library|cc_library|idk_cc_source_library\w*)\(\s*$", re.M)

