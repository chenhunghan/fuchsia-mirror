    combined = bazel_src + "\n" + base_text(gn_rel)
    gn_path = os.path.join(workdir, gn_rel)
    if os.path.isfile(gn_path):
        with open(gn_path, encoding="utf-8", errors="replace") as gf:
            combined += "\n" + gf.read()
    candidates = []
    seen = set()
    for fname in re.findall(r'"([A-Za-z0-9_./-]+\.[A-Za-z0-9_.-]+)"', combined):
        if fname in seen or fname.startswith(("/", ":", "@", "$")):
            continue
        if fname.endswith(SKIP_LIST_FILE_EXTS):
            continue
        seen.add(fname)
        fpath = os.path.join(workdir, d, fname)
        if not os.path.isfile(fpath) or os.path.getsize(fpath) > 65536:
            continue
        with open(fpath, encoding="utf-8", errors="replace") as lf:
            raw_entries = [
                ln.split("#", 1)[0].strip() for ln in lf.read().splitlines()
            ]
        entries = [
            e
            for e in raw_entries
            if e and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.$@:-]*", e)
        ]
        if 2 <= len(entries) <= 200:
            candidates.append((fname, entries))
    return candidates


# Check hardcoded Starlark list attributes derived from a local list/allowlist file
def check_inlined_file_lists(d, rel, text):
    list_files = collect_local_list_files(d, text)
    if not list_files:
        return
    lines = text.splitlines()
    for m in re.finditer(
        r"^[ \t]+([a-z_][a-z0-9_]*)\s*=\s*\[(.*?)\]", text, re.M | re.S
    ):
        attr = m.group(1)
        if attr in NON_FLAG_LIST_ATTRS:
            continue
        items = re.findall(r'"([^"]+)"', m.group(2))
        if len(items) < 2:
            continue
        start_idx = text[: m.start()].count("\n")
        end_idx = text[: m.end()].count("\n")
        window = "\n".join(
            lines[max(0, start_idx - 5) : min(len(lines), end_idx + 5)]
        )
        for fname, entries in list_files:
            matched = sum(1 for sym in entries if any(sym in it for it in items))
            if matched < max(2, (len(entries) + 1) // 2):
                continue
            has_if = bool(re.search(r"#\s*LINT\.IfChange\b", window))
            has_then = bool(
                re.search(
                    r"#\s*LINT\.ThenChange\([^)]*"
                    + re.escape(os.path.basename(fname))
                    + r"[^)]*\)",
                    window,
                )
            )
            if has_if and has_then:
                continue
            _emit(
                findings,
                "inlined_file_list_missing_ifttt",
                "WARNING",
                rel,
                start_idx + 1,
                f"`{attr} = [...]` hardcodes entries from `{fname}` without a "
                f"`# LINT.IfChange` / `# LINT.ThenChange({fname})` pair to keep "
                "both copies in sync.",
                INLINED_LIST_IFTTT_REMEDIATION,
            )


# Find the nearest enclosing Bazel package directory for an in-tree include path
def find_enclosing_bazel_pkg(inc):
    cur = os.path.dirname(inc)
    while cur:
        if os.path.isfile(os.path.join(workdir, cur, "BUILD.bazel")):
            return cur
        parent = os.path.dirname(cur)
        if parent == cur:
            break
        cur = parent
    return ""


# Build remediation for an upstream BUILD.bazel / BUILD.gn header parity mismatch.
def _build_upstream_header_remediation(inc_pkg, up_bz_rel, rel_hdr, missing_in_gn_only):
    up_gn_rel = f"{inc_pkg}/BUILD.gn"
    gn_check_note = (
        f" If claiming `\"{rel_hdr}\"` in `{up_gn_rel}` causes `gn check` to fail "
        f"on an existing GN target that already `#include`s `{inc_pkg}/{rel_hdr}` "
        f"without depending on `//{inc_pkg}`, add `\"//{inc_pkg}\"` to that "
        "target's `deps` or `public_deps`."
    )
    if missing_in_gn_only:
        return (
            "Remove `# @bazel2gn:skip` (and any accompanying skip comment) from "
            f'`"{rel_hdr}"` in `hdrs` of `{up_bz_rel}`, preserving all '
            "pre-existing rules and `default_visibility` unchanged, then run "
            f"`fx bazel2gn -d {inc_pkg}` so `{up_gn_rel}` includes "
            f'`"{rel_hdr}"` in GN `public` as well.' + gn_check_note
        )
    return (
        f'Make a minimal, surgical edit in `{up_bz_rel}` adding `"{rel_hdr}"` '
        "(without `# @bazel2gn:skip`) to `hdrs` of the owning C/C++ library "
        "target (preserving all pre-existing rule macros and "
        "`default_visibility` unchanged), then run "
        f"`fx bazel2gn -d {inc_pkg}` if `{up_gn_rel}` contains "
        "`BAZEL2GN SENTINEL` so both Bazel and GN include the header."
        + gn_check_note
    )


# Check #included headers omitted from hdrs (or skipped from GN public) in upstream packages.
def check_undeclared_upstream_cc_headers(d, rel, text):
    cc_call_re = re.compile(
        r"^((?:fx_cc_|cc_|idk_cc_)[a-z0-9_]*)\(\s*$", re.M
    )
    inc_re = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)
    target_set = set(target_dirs)
    reported = set()
    pkg_cache = {}

    for m in cc_call_re.finditer(text):
        block = block_at(text, m.end() - 1)
        dep_labels = list_attr(block, "deps") + list_attr(block, "implementation_deps")
        dep_pkgs = {
            lab.lstrip("@").split(":", 1)[0].strip("/")
            for lab in dep_labels
            if not lab.startswith(":")
        }
        if not dep_pkgs:
            continue

        all_includes = set()
        for src_or_hdr in list_attr(block, "srcs") + list_attr(block, "hdrs"):
            if src_or_hdr.startswith((":", "//", "@")):
                continue
            fpath = os.path.join(workdir, d, src_or_hdr)
            if not os.path.isfile(fpath):
                continue
            with open(fpath, encoding="utf-8", errors="replace") as sf:
                all_includes.update(inc_re.findall(sf.read()))

        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        tname = name_m.group(1) if name_m else "?"
        line = text[: m.start()].count("\n") + 1

        for inc in sorted(all_includes):
            if "/" not in inc or not os.path.isfile(os.path.join(workdir, inc)):
                continue
            inc_pkg = find_enclosing_bazel_pkg(inc)
            if not inc_pkg or inc_pkg in target_set or inc_pkg not in dep_pkgs:
                continue
            if inc_pkg.startswith(("third_party/", "prebuilt/", "out/", "build/")):
                continue
            rel_hdr = os.path.relpath(
                os.path.join(workdir, inc), os.path.join(workdir, inc_pkg)
            ).replace(os.sep, "/")
            up_bz_rel = f"{inc_pkg}/BUILD.bazel"
            up_gn_rel = f"{inc_pkg}/BUILD.gn"
            if up_bz_rel not in pkg_cache:
                with open(
                    os.path.join(workdir, up_bz_rel), encoding="utf-8", errors="replace"
                ) as uf:
                    cur_bz = uf.read()
                cur_gn = ""
                if os.path.isfile(os.path.join(workdir, up_gn_rel)):
                    with open(
                        os.path.join(workdir, up_gn_rel), encoding="utf-8", errors="replace"
                    ) as gf:
                        cur_gn = gf.read()
                pkg_cache[up_bz_rel] = (cur_bz, cur_gn)
            up_bz_text, up_gn_text = pkg_cache[up_bz_rel]
            if "glob(" in up_bz_text:
                continue
            has_sentinel = "BAZEL2GN SENTINEL" in up_gn_text
            missing_in_bz = f'"{rel_hdr}"' not in up_bz_text
            missing_in_gn_only = (
                not missing_in_bz
                and has_sentinel
                and f'"{rel_hdr}"' not in up_gn_text
            )
            if not missing_in_bz and not missing_in_gn_only:
                continue
            key = (inc_pkg, rel_hdr)
            if key in reported:
                continue
            reported.add(key)
            if missing_in_gn_only:
                hdr_line = next(
                    (
                        idx + 1
                        for idx, ln in enumerate(up_bz_text.splitlines())
                        if f'"{rel_hdr}"' in ln
                    ),
                    1,
                )
                finding_file = up_bz_rel
                finding_line = hdr_line
                msg = (
                    f'`"{rel_hdr}"` in `{up_bz_rel}` (included as "{inc}" by '
                    f'{m.group(1)}(name = "{tname}") in `{rel}`) is skipped from '
                    f"GN generation and missing from `{up_gn_rel}`; real headers "
                    f"needed by `//{inc_pkg}` must be included in GN (`public`) "
                    "as well as Bazel (`hdrs`)."
                )
            else:
                finding_file = rel
                finding_line = line
                msg = (
                    f'{m.group(1)}(name = "{tname}") includes "{inc}", which '
                    f'exists on disk under already-migrated dependency "//{inc_pkg}" '
                    f'as "{rel_hdr}", but "{rel_hdr}" is omitted from hdrs in '
                    f"{up_bz_rel} (causing Bazel sandbox compile failure: "
                    f"fatal error: '{inc}' file not found)."
                )
            rem = _build_upstream_header_remediation(
                inc_pkg, up_bz_rel, rel_hdr, missing_in_gn_only
            )
            _emit(
                findings,
                "undeclared_upstream_cc_header",
                "ERROR",
                finding_file,
                finding_line,
                msg,
                rem,
            )

    check_missing_or_skipped_cc_header_deps(d, rel, text)


# Normalize a Bazel dependency label relative to `cur_pkg` into `//<pkg>:<target>`.
def _norm_bz_cc_dep(lab, cur_pkg):
    s = (lab or "").strip()
    if not s or (s.startswith("@") and not s.startswith("@//")):
        return ""
    if s.startswith("@//"):
        s = s[1:]
    if s.startswith(":"):
        return f"//{cur_pkg}:{s[1:]}"
    if s.startswith("//"):
        body = s[2:]
        p, sep, t = body.partition(":")
        p = p.strip("/")
        t = t if sep else p.rsplit("/", 1)[-1]
        return f"//{p}:{t}" if p and t else ""
    return ""


# Check C/C++ #include paths owned by an in-tree BUILD.bazel C/C++ library target
# whose target is missing from `deps` or marked `# @bazel2gn:skip` on a dual-built target.
def check_missing_or_skipped_cc_header_deps(d, rel, text):
    cc_call_re = re.compile(
        r"^((?:fx_cc_|cc_|idk_cc_)[a-z0-9_]*)\(\s*$", re.M
    )
    inc_re = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)
    pkg_info_cache = {}
    reported = set()

    def _get_pkg_cc_info(pkg):
        if pkg in pkg_info_cache:
            return pkg_info_cache[pkg]
        bz_path = os.path.join(workdir, pkg, "BUILD.bazel")
        gn_path = os.path.join(workdir, pkg, "BUILD.gn")
        bz_txt = ""
        gn_txt = ""
        if os.path.isfile(bz_path):
            with open(bz_path, encoding="utf-8", errors="replace") as bf:
                bz_txt = bf.read()
        if os.path.isfile(gn_path):
            with open(gn_path, encoding="utf-8", errors="replace") as gf:
                gn_txt = gf.read()
        hdr_owners = {}
        target_deps = {}
        target_unskipped_deps = {}
        if bz_txt and "glob(" not in bz_txt:
            private_cc_targets = set()
            for cm in cc_call_re.finditer(bz_txt):
                cblock = block_at(bz_txt, cm.end() - 1)
                nm = re.search(r'^\s+name\s*=\s*"([^"]+)"', cblock, re.M)
                if not nm:
                    continue
                cname = nm.group(1)
                cnorm = f"//{pkg}:{cname}"
                pre_start = max(0, cm.start() - 120)
                target_skipped = "@bazel2gn:skip" in bz_txt[pre_start : cm.end()]
                vis_items = list_attr(cblock, "visibility")
                if re.search(r"^\s+visibility\s*=\s*\[\s*\]", cblock, re.M) or (
                    vis_items == ["//visibility:private"]
                ):
                    private_cc_targets.add(cname)
                for h in list_attr(cblock, "hdrs") + list_attr(cblock, "textual_hdrs"):
                    if not h.startswith((":", "//", "@")):
                        hdr_owners.setdefault(h, []).append((cname, target_skipped))
                cdeps = {
                    _norm_bz_cc_dep(dep, pkg)
                    for dep in list_attr(cblock, "deps")
                } - {""}
                target_deps[cnorm] = cdeps
                skipped_in_block = set()
                for ln in cblock.splitlines():
                    if "@bazel2gn:skip" in ln:
                        for q in re.findall(r'"([^"]+)"', ln):
                            qn = _norm_bz_cc_dep(q, pkg)
                            if qn:
                                skipped_in_block.add(qn)
                target_unskipped_deps[cnorm] = (
                    set() if target_skipped else (cdeps - skipped_in_block)
                )
            # Follow Bazel `alias(name = ..., actual = ...)` forwarding targets so
            # dependencies on public aliases reach the underlying C/C++ library's
            # headers and public `deps`.
            for am in re.finditer(r"^alias\(\s*$", bz_txt, re.M):
                ablock = block_at(bz_txt, am.end() - 1)
                nm = re.search(r'\bname\s*=\s*"([^"]+)"', ablock)
                act_m = re.search(r'\bactual\s*=\s*"([^"]+)"', ablock)
                if not nm or not act_m:
                    continue
                aname = nm.group(1)
                anorm = f"//{pkg}:{aname}"
                act_norm = _norm_bz_cc_dep(act_m.group(1), pkg)
                if not act_norm:
                    continue
                pre_start = max(0, am.start() - 120)
                alias_skipped = "@bazel2gn:skip" in bz_txt[pre_start : am.end()]
                target_deps.setdefault(anorm, set()).add(act_norm)
                if not alias_skipped:
                    target_unskipped_deps.setdefault(anorm, set()).add(act_norm)
                act_pkg, _, act_tname = act_norm[2:].partition(":")
                if act_pkg == pkg and act_tname:
                    for owners in hdr_owners.values():
                        if any(o == act_tname for o, _ in owners):
                            if act_tname in private_cc_targets:
                                owners.insert(0, (aname, alias_skipped))
                            else:
                                owners.append((aname, alias_skipped))
        info = (bz_txt, gn_txt, hdr_owners, target_deps, target_unskipped_deps)
        pkg_info_cache[pkg] = info
        return info

    _, cur_gn_txt, _, _, _ = _get_pkg_cc_info(d)
    cur_has_sentinel = "BAZEL2GN SENTINEL" in cur_gn_txt

    for m in cc_call_re.finditer(text):
        block = block_at(text, m.end() - 1)
        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        if not name_m:
            continue
        tname = name_m.group(1)
        rule_name = m.group(1)
        line = text[: m.start()].count("\n") + 1
        pre_start = max(0, m.start() - 120)
        is_target_skipped = "@bazel2gn:skip" in text[pre_start : m.end()]

        dep_labels = list_attr(block, "deps") + list_attr(block, "implementation_deps")
        direct_norms = {_norm_bz_cc_dep(lab, d) for lab in dep_labels} - {""}
        skipped_line_by_norm = {}
        block_start_line = text[: m.end() - 1].count("\n") + 1
        for idx, ln in enumerate(block.splitlines()):
            if "@bazel2gn:skip" in ln:
                for q in re.findall(r'"([^"]+)"', ln):
                    qn = _norm_bz_cc_dep(q, d)
                    if qn in direct_norms:
                        skipped_line_by_norm[qn] = (q, block_start_line + idx)

        reached_bz = set(direct_norms)
        reached_gn = set(direct_norms - set(skipped_line_by_norm))
        for _ in range(3):
            for dn in list(reached_bz):
                dpkg = dn[2:].split(":", 1)[0]
                _, _, _, t_deps, _ = _get_pkg_cc_info(dpkg)
                reached_bz |= t_deps.get(dn, set())
            for dn in list(reached_gn):
                dpkg = dn[2:].split(":", 1)[0]
                _, _, _, _, t_unskipped = _get_pkg_cc_info(dpkg)
                reached_gn |= t_unskipped.get(dn, set())

        own_files = set(
            list_attr(block, "srcs")
            + list_attr(block, "hdrs")
            + list_attr(block, "textual_hdrs")
        )
        for src_or_hdr in list_attr(block, "srcs") + list_attr(block, "hdrs"):
            if src_or_hdr.startswith((":", "//", "@")):
                continue
            fpath = os.path.join(workdir, d, src_or_hdr)
            if not os.path.isfile(fpath):
                continue
            with open(fpath, encoding="utf-8", errors="replace") as sf:
                incs = inc_re.findall(sf.read())
            for inc in sorted(set(incs)):
                if "/" not in inc or not os.path.isfile(os.path.join(workdir, inc)):
                    continue
                inc_pkg = find_enclosing_bazel_pkg(inc)
                if not inc_pkg or inc_pkg.startswith(
                    ("third_party/", "prebuilt/", "out/", "build/", "sdk/")
                ):
                    continue
                rel_hdr = os.path.relpath(
                    os.path.join(workdir, inc), os.path.join(workdir, inc_pkg)
                ).replace(os.sep, "/")
                if inc_pkg == d and rel_hdr in own_files:
                    continue
                up_bz, up_gn, hdr_owners, _, _ = _get_pkg_cc_info(inc_pkg)
                if not up_bz or "glob(" in up_bz:
                    continue
                owners = hdr_owners.get(rel_hdr, [])
                if not owners:
                    continue
                non_skip_owners = [o for o, sk in owners if not sk]
                cand_owners = non_skip_owners or [o for o, _ in owners]
                owner_norms = {f"//{inc_pkg}:{o}" for o in cand_owners}

                if not (owner_norms & reached_bz):
                    primary_owner = cand_owners[0]
                    if inc_pkg == d:
                        sug_lbl = f":{primary_owner}"
                    elif primary_owner == inc_pkg.rsplit("/", 1)[-1]:
                        sug_lbl = f"//{inc_pkg}"
                    else:
                        sug_lbl = f"//{inc_pkg}:{primary_owner}"
                    key = ("missing", rel, tname, inc_pkg, primary_owner)
                    if key in reported:
                        continue
                    reported.add(key)
                    msg = (
                        f'{rule_name}(name = "{tname}") includes "{inc}" '
                        f'(in `{src_or_hdr}`), which is exported in `hdrs` by '
                        f'`//{inc_pkg}:{primary_owner}`, but "{tname}" does not '
                        f'depend on `//{inc_pkg}:{primary_owner}` (causing Bazel '
                        f'sandbox compilation or `gn check` to fail).'
                    )
                    rem = (
                        f'Add `"{sug_lbl}"` (without `# @bazel2gn:skip`) to `deps` '
                        f'of `{rule_name}(name = "{tname}")` in `{rel}` (and add '
                        f'`target_compatible_with = HOST_CONSTRAINTS` or '
                        f'`FUCHSIA_CONSTRAINTS` if `{tname}` is unrestricted and '
                        f'`{sug_lbl}` is platform-restricted), then run '
                        f'`fx bazel2gn -d {d}`.'
                    )
                    _emit(
                        findings,
                        "missing_cc_header_dep",
                        "ERROR",
                        rel,
                        line,
                        msg,
                        rem,
                    )
                elif (
                    not is_target_skipped
                    and cur_has_sentinel
                    and f'"{tname}"' in cur_gn_txt
                    and f'"{rel_hdr}"' in up_gn
                    and not (owner_norms & reached_gn)
                    and (owner_norms & set(skipped_line_by_norm))
                ):
                    sk_norm = sorted(owner_norms & set(skipped_line_by_norm))[0]
                    raw_dep_str, sk_line = skipped_line_by_norm[sk_norm]
                    key = ("skipped", rel, tname, sk_norm)
                    if key in reported:
                        continue
                    reported.add(key)
                    msg = (
                        f'{rule_name}(name = "{tname}") in `{rel}` marks dependency '
                        f'`"{raw_dep_str}"` with `# @bazel2gn:skip`, omitting it from '
                        f'`{d}/BUILD.gn` even though `{src_or_hdr}` includes '
                        f'`"{inc}"` (claimed by `{inc_pkg}/BUILD.gn`), which causes '
                        f'`gn check` (`fx build` / `fx gen`) to fail with '
                        f'`Include not allowed`.'
                    )
                    rem = (
                        f'Remove `# @bazel2gn:skip` from `"{raw_dep_str}"` on '
                        f'`{rule_name}(name = "{tname}")` in `{rel}` and run '
                        f'`fx bazel2gn -d {d}` so the C/C++ header dependency is '
                        f'synced to `{d}/BUILD.gn`.'
                    )
                    _emit(
                        findings,
                        "skipped_cc_header_dep",
                        "ERROR",
                        rel,
                        sk_line,
                        msg,
                        rem,
                    )


# Check upstream idk_cc_source_library_zx dependencies whose public headers
# include <zircon/...> without non_fuchsia_deps = ["//zircon/system/public"]
# when the migrated package builds or tests on host (https://fxbug.dev/429377203).
def check_upstream_zx_host_public_deps(d, rel, text):
    gn_path = os.path.join(workdir, d, "BUILD.gn")
    gn_src = ""
    if os.path.isfile(gn_path):
        try:
            with open(gn_path, encoding="utf-8", errors="replace") as gf:
                gn_src = gf.read()
        except OSError:
            gn_src = ""
    has_host_surface = (
        any(
            tok in text
            for tok in (
                "host_rustc_test",
                "host_cc_test",
                "host_test",
                "HOST_OS_CONSTRAINTS",
            )
        )
        or "$host_toolchain" in gn_src
        or "is_host" in gn_src
    )
    if not has_host_surface:
        return

    dep_pkgs = set()
    for lbl in re.findall(r'"//([A-Za-z0-9_./-]+)(?::[^"]*)?"', text):
        pkg = lbl.strip("/")
        if pkg and pkg not in target_dirs:
            dep_pkgs.add(pkg)

    zx_inc_re = re.compile(r'^\s*#\s*include\s*[<"](zircon/[^>"]+)[>"]', re.M)
    for dep_pkg in sorted(dep_pkgs):
        up_bz_rel = f"{dep_pkg}/BUILD.bazel"
        up_bz_path = os.path.join(workdir, up_bz_rel)
        if not os.path.isfile(up_bz_path):
            continue
        try:
            with open(up_bz_path, encoding="utf-8", errors="replace") as uf:
                up_bz = uf.read()
        except OSError:
            continue
        if "idk_cc_source_library_zx(" not in up_bz:
            continue
        for zm in re.finditer(r"^idk_cc_source_library_zx\(\s*$", up_bz, re.M):
            zblock = block_at(up_bz, zm.end() - 1)
            if (
                "non_fuchsia_deps" in zblock
                or "//zircon/system/public" in zblock
                or "//sdk/lib/zircon-assert" in zblock
            ):
                continue
            zname_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', zblock, re.M)
            zname = zname_m.group(1) if zname_m else os.path.basename(dep_pkg)
            missing_zx_hdr = None
            for hdr in list_attr(zblock, "hdrs"):
                hdr_path = os.path.join(workdir, dep_pkg, hdr)
                if not os.path.isfile(hdr_path):
                    continue
                try:
                    with open(hdr_path, encoding="utf-8", errors="replace") as hf:
                        hdr_src = hf.read()
                except OSError:
                    continue
                for zm_inc in zx_inc_re.findall(hdr_src):
                    if os.path.isfile(
                        os.path.join(workdir, "zircon/system/public", zm_inc)
                    ):
                        missing_zx_hdr = (hdr, zm_inc)
                        break
                if missing_zx_hdr:
                    break
            if not missing_zx_hdr:
                continue
            hdr_rel, zx_inc = missing_zx_hdr
            msg = (
                f"`{rel}` has host targets/tests depending on `//{dep_pkg}`, where "
                f'`idk_cc_source_library_zx(name = "{zname}")` in `{up_bz_rel}` '
                f"declares `{hdr_rel}` (`#include <{zx_inc}>`) without "
                '`non_fuchsia_deps = ["//zircon/system/public"]` '
                "(https://fxbug.dev/429377203), causing `--config=host` compiles to "
                f"fail with `'{zx_inc}' file not found`."
            )
            rem = (
                f'In `{up_bz_rel}`, add documented `# @bazel2gn:skip` '
                '`non_fuchsia_deps = ["//zircon/system/public"]` to '
                f'`idk_cc_source_library_zx(name = "{zname}")`:\n'
                f"    # Needed on host in Bazel for <{zx_inc}> "
                "(https://fxbug.dev/429377203).\n"
                "    # @bazel2gn:skip\n"
                '    non_fuchsia_deps = ["//zircon/system/public"],\n'
                f"Leave `{dep_pkg}/BUILD.gn` unchanged (GN's `zx_library()` already "
                "adds `//zircon/system/public` on `!is_fuchsia`)."
            )
            _emit(
                findings,
                "missing_upstream_zx_host_public_dep",
                "ERROR",
                rel,
                1,
                msg,
                rem,
            )


