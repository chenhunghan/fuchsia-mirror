# Check for test-only environment exclusion TODOs left on a rustc_library target
# whose unit test was split into a separate rustc_test target.
def check_orphaned_library_test_env_todo(d, rel, text):
    base_src = base_text(rel)
    base_blocks = {
        "\n".join(ln.strip() for ln in blk[3])
        for blk in _extract_comment_blocks(base_src)
    }
    line_offsets = [0]
    for ln in text.splitlines(True):
        line_offsets.append(line_offsets[-1] + len(ln))
    for start, _, _, raw, next_idx, next_line in _extract_comment_blocks(text):
        norm_blk = "\n".join(ln.strip() for ln in raw)
        if norm_blk in base_blocks or next_idx is None:
            continue
        rm = re.match(
            r"^\s*(rustc_library|rust_library|rustc_staticlib)\(\s*$", next_line
        )
        if not rm:
            continue
        hit_line = None
        hit_text = ""
        for offset, ln in enumerate(raw):
            if TEST_ENV_TODO_RE.search(ln):
                hit_line = start + offset + 1
                hit_text = ln.strip()
                break
        if hit_line is None:
            continue
        call_pos = line_offsets[next_idx] + next_line.find("(")
        blk_text = block_at(text, call_pos)
        if (
            "exclude_toolchain_tags" in blk_text
            or "with_unit_tests" in blk_text
            or "exclude_toolchain_tags" in norm_blk
        ):
            continue
        nm = re.search(r'^\s+name\s*=\s*"([^"]+)"', blk_text, re.M)
        tname = nm.group(1) if nm else "?"
        msg = (
            f"Comment `{hit_text}` on `{rm.group(1)}(name = \"{tname}\")` in "
            f"`{rel}` documents `exclude_toolchain_tags`, which in GN `rustc_library` "
            "applied only to the unit test target and is no longer present on the "
            "library target."
        )
        rem = (
            f"Remove `{hit_text}` from `{rm.group(1)}(name = \"{tname}\")` in "
            f"`{rel}` and keep it only on the `rustc_test` target alongside "
            '`tags = ["exclude_toolchain_tags=..."]`.'
        )
        _emit(
            findings,
            "orphaned_test_env_todo_on_library",
            "ERROR",
            rel,
            hit_line,
            msg,
            rem,
        )


