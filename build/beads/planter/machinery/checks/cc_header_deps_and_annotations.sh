def base_text(rel):
    """Returns the file at $PLANTER_CHANGE_BASE, or "" when it did not exist."""
    if not change_base:
        return ""
    try:
        return subprocess.run(
            ["git", "-C", workdir, "show", f"{change_base}:{rel}"],
            capture_output=True, text=True, check=True).stdout
    except subprocess.CalledProcessError:
        return ""


def block_at(text, start):
    depth = 0
    for i in range(start, len(text)):
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
    return text[start:]


def list_attr(block, attr):
    m = re.search(r"^\s+" + attr + r"\s*=\s*\[(.*?)\]", block, re.M | re.S)
    if not m:
        return []
    return re.findall(r'"([^"]+)"', m.group(1))


# Check undocumented # @bazel2gn: directives
def is_plain_comment(line):
    s = line.strip()
    return s.startswith("#") and not DIRECTIVE_RE.search(s) and len(s.lstrip("#").strip()) > 0


def is_directive_only(line):
    s = line.strip()
    return s.startswith("#") and DIRECTIVE_RE.search(s) is not None


def opening_line(lines, idx):
    """For a closing `]`/`)` line, returns the index of the line that opened it."""
    depth = 0
    for j in range(idx, -1, -1):
        code = lines[j].split("#", 1)[0]
        depth += code.count("]") + code.count(")") - code.count("[") - code.count("(")
        if depth <= 0 and j != idx:
            return j
    return None


def documented(lines, idx):
    anchors = [idx]
    code = lines[idx].split("#", 1)[0].strip()
    if code.startswith("]") or code.startswith(")"):
        op = opening_line(lines, idx)
        if op is not None:
            anchors.append(op)
    # Also accept a comment placed on the local placeholder filegroup("<name>")
    # definition when `# @bazel2gn:path_overwrite:` is attached to `":<name>"`.
    m_local_lbl = re.search(r'":([A-Za-z0-9_.-]+)"', code)
    if m_local_lbl and "@bazel2gn:path_overwrite:" in lines[idx]:
        fg_name = m_local_lbl.group(1)
        fg_pat = re.compile(r'^\s*name\s*=\s*"' + re.escape(fg_name) + r'"')
        for k, kline in enumerate(lines):
            if fg_pat.search(kline):
                op_fg = opening_line(lines, k)
                if op_fg is not None and "filegroup" in lines[op_fg]:
                    anchors.append(op_fg)
                break
    for a in anchors:
        j = a - 1
        while j >= 0 and is_directive_only(lines[j]):
            j -= 1
        if j >= 0 and is_plain_comment(lines[j]):
            return True
    return False


# Check whether a path_overwrite directive maps an fx_packaged_binary wrapper
# label back to its underlying executable/rustc_binary target label in GN.
_FX_PACKAGED_BIN_CACHE = {}


def _is_fx_packaged_binary_overwrite(d, line):
    m_dir = re.search(r"#\s*@bazel2gn:path_overwrite:([^\s#]+)", line)
    if not m_dir:
        return False
    code_part = line.split("#", 1)[0]
    m_lbl = re.search(r'"([^"]+)"', code_part)
    if not m_lbl:
        return False
    bz_lbl = m_lbl.group(1).strip()
    raw_clean = bz_lbl[1:] if bz_lbl.startswith("@") else bz_lbl
    if raw_clean.startswith("//"):
        body = raw_clean[2:]
        if ":" in body:
            dep_pkg, dep_name = body.split(":", 1)
        else:
            dep_pkg = body.strip("/")
            dep_name = os.path.basename(dep_pkg)
    elif raw_clean.startswith(":"):
        dep_pkg, dep_name = d, raw_clean[1:]
    else:
        return False
    dep_pkg = dep_pkg.strip("/")
    dep_bz = os.path.join(workdir, dep_pkg, "BUILD.bazel")
    if dep_bz not in _FX_PACKAGED_BIN_CACHE:
        try:
            with open(dep_bz, encoding="utf-8", errors="replace") as df:
                _FX_PACKAGED_BIN_CACHE[dep_bz] = df.read()
        except OSError:
            _FX_PACKAGED_BIN_CACHE[dep_bz] = ""
    dep_src = _FX_PACKAGED_BIN_CACHE[dep_bz]
    if "fx_packaged_binary" not in dep_src:
        return False
    for cm in re.finditer(r"^fx_packaged_binary\(\s*$", dep_src, re.M):
        blk = block_at(dep_src, cm.end() - 1)
        nm = re.search(r'^\s+name\s*=\s*"([^"]+)"', blk, re.M)
        if nm and nm.group(1) == dep_name:
            return True
    return False


# Collect documented @bazel2gn: directive keys from a single BUILD.bazel file.
def collect_documented_directive_keys(text):
    keys = set()
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = DIRECTIVE_RE.search(line)
        if m and documented(lines, i):
            keys.add(m.group(0).strip())
    return keys


def check_directives(d, rel, text, shared_documented_keys=None):
    base_lines = set(l.strip() for l in base_text(rel).splitlines())
    lines = text.splitlines()
    documented_keys = set(shared_documented_keys or ())
    pending = []
    for i, line in enumerate(lines):
        m = DIRECTIVE_RE.search(line)
        if not m:
            continue
        if (
            m.group(1) == "skip"
            and "target_compatible_with" in line
            and "HOST_OS_CONSTRAINTS" in line
        ):
            # Handled by bazel_minimality (skipped_host_os_constraints); do not
            # tell the coder to add a comment justifying the skip.
            continue
        if _is_fx_packaged_binary_overwrite(d, line):
            continue
        key = m.group(0).strip()
        if documented(lines, i):
            documented_keys.add(key)
        elif line.strip() not in base_lines and not (
            # Directives that redundant_builtin_label_directive, bazel_minimality
            # (cc_binary_/rustc_test_raw_output_name_annotation) or migration_sanity
            # (redundant_bazel2gn_skip) require removing must not also be asked to
            # gain a justifying comment. Also exempt `# @bazel2gn:skip` above
            # Bazel `test_suite()` targets, which routinely omit comments.
            _redundant_builtin_label_hit(lines, i, BUILTIN_LABEL_MAP)
            or _raw_output_name_on_native_rule(lines, i)
            or _skip_on_no_gn_equiv_rule(lines, i)
            or _skip_on_bazel_test_suite(lines, i)
        ):
            pending.append((i, m.group(1), key))
    has_gn_file = os.path.isfile(os.path.join(workdir, d, "BUILD.gn"))
    remediation = (
        DIRECTIVE_REMEDIATION if has_gn_file else DELETED_GN_DIRECTIVE_REMEDIATION
    )
    for i, kind, key in pending:
        if key in documented_keys:
            continue
        _emit(
            findings,
            "undocumented_bazel2gn_directive",
            "WARNING",
            rel,
            i + 1,
            f"New `# @bazel2gn:{kind}` directive has no comment explaining "
            "why the generated GN differs from Bazel here.",
            remediation,
        )


# Check public headers whose includes come from implementation_deps
def include_matches_label(includes, label):
    lab = label.lstrip("@")
    pkg, _, name = lab.partition(":")
    pkg = pkg.strip("/")
    last = pkg.rsplit("/", 1)[-1]
    name = name or last
    # FIDL bindings: HLCPP <fuchsia/io/cpp/fidl.h>, new C++ <fidl/fuchsia.io/cpp/...>.
    fm = re.match(r"(.+)_(hlcpp|cpp)$", name)
    if fm and (pkg.startswith("sdk/fidl/") or last == fm.group(1)):
        lib, flavor = fm.group(1), fm.group(2)
        for inc in includes:
            if flavor == "hlcpp" and inc.startswith(lib.replace(".", "/") + "/cpp/"):
                return inc, "ERROR"
            if flavor == "cpp" and inc.startswith(f"fidl/{lib}/cpp/"):
                return inc, "ERROR"
        return None
    # Common Fuchsia layouts: //<...>/<x> exports <x/...> or <lib/<x>/...>.
    for inc in includes:
        if last and (inc.startswith(f"{last}/") or inc.startswith(f"lib/{last}/")):
            return inc, "WARNING"
    return None


def check_header_deps(d, rel, text):
    for m in CC_RULE_RE.finditer(text):
        block = block_at(text, m.end() - 1)
        impl = list_attr(block, "implementation_deps")
        if not impl:
            continue
        deps = set(list_attr(block, "deps"))
        includes = []
        for h in list_attr(block, "hdrs"):
            if h.startswith(":") or h.startswith("//") or h.startswith("@"):
                continue
            path = os.path.join(workdir, d, h)
            if not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as f:
                includes += re.findall(r'^\s*#\s*include\s*<([^>]+)>', f.read(), re.M)
        if not includes:
            continue
        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        name = name_m.group(1) if name_m else "?"
        line = text[:m.start()].count("\n") + 1
        for label in impl:
            if label in deps:
                continue
            hit = include_matches_label(includes, label)
            if not hit:
                continue
            inc, severity = hit
            _emit(
                findings,
                "public_header_dep_in_implementation_deps",
                severity,
                rel,
                line,
                f'{m.group(1)}(name = "{name}") lists "{label}" in '
                f"implementation_deps, but a header in hdrs includes <{inc}>, "
                "so dependents need it (GN public_deps).",
                HEADER_REMEDIATION,
            )
    check_non_testonly_fidl_cpp_testing_deps(d, rel, text)


NON_TEST_CC_RULE_RE = re.compile(
    r"^(fx_cc_library|fx_cc_binary|cc_library|cc_binary|fuchsia_cc_driver|"
    r"idk_cc_source_library\w*|idk_cc_shared_library\w*|idk_cc_static_library\w*|"
    r"idk_cc_binary_host_tool|cc_binary_host_tool)\(\s*$",
    re.M,
)
FIDL_TEST_BASE_INC_RE = re.compile(
    r"^\s*#\s*include\s*<(fidl/[^/>]+/cpp/(?:driver/)?(?:wire_)?test_base\.h)>",
    re.M,
)


# Check non-testonly C/C++ targets depending on testonly <fidl>_cpp_testing targets
# or including <fidl/.../cpp/*test_base.h> headers.
def check_non_testonly_fidl_cpp_testing_deps(d, rel, text):
    if re.search(r"\bdefault_testonly\s*=\s*True\b", text):
        return
    lines = text.splitlines()
    for m in NON_TEST_CC_RULE_RE.finditer(text):
        block = block_at(text, m.end() - 1)
        if re.search(r"^\s+testonly\s*=\s*True\b", block, re.M):
            continue
        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        tname = name_m.group(1) if name_m else "?"
        rule_line = text[: m.start()].count("\n") + 1
        all_deps = list_attr(block, "deps") + list_attr(block, "implementation_deps")
        testing_deps = [lab for lab in all_deps if lab.endswith("_cpp_testing")]
        test_base_incs = []
        for src_or_hdr in list_attr(block, "srcs") + list_attr(block, "hdrs"):
            if src_or_hdr.startswith((":", "//", "@")):
                continue
            fpath = os.path.join(workdir, d, src_or_hdr)
            if not os.path.isfile(fpath):
                continue
            with open(fpath, encoding="utf-8", errors="replace") as sf:
                for inc in FIDL_TEST_BASE_INC_RE.findall(sf.read()):
                    test_base_incs.append((src_or_hdr, inc))
        if not testing_deps and not test_base_incs:
            continue
        rep_line = rule_line
        if testing_deps:
            first_dep = f'"{testing_deps[0]}"'
            for idx in range(rule_line - 1, len(lines)):
                if first_dep in lines[idx]:
                    rep_line = idx + 1
                    break
        dep_desc = (
            "depends on testonly FIDL C++ testing target(s) "
            + ", ".join(f'`"{lab}"`' for lab in testing_deps)
            if testing_deps
            else "is not `testonly = True`"
        )
        inc_desc = (
            " and includes "
            + ", ".join(f"`<{inc}>` in `{src}`" for src, inc in test_base_incs)
            if test_base_incs
            else ""
        )
        src_files = sorted({f"{d}/{src}" for src, _ in test_base_incs})
        src_hint = (
            f"from {', '.join(f'`{s}`' for s in src_files)} "
            f"(and run `fx format-code --changed-lines --files={','.join(src_files)}`)"
            if src_files
            else "from the C/C++ source/header file"
        )
        _emit(
            findings,
            "non_testonly_fidl_cpp_testing_dep",
            "ERROR",
            rel,
            rep_line,
            f'{m.group(1)}(name = "{tname}") is not `testonly = True`, but '
            f"{dep_desc}{inc_desc}. In Bazel (`//build/bazel/rules/fidl:"
            "fidl_cc_library.bzl`), `<fidl>_cpp_testing` targets (which expose "
            "`test_base.h` and `wire_test_base.h`) are unconditionally "
            "`testonly = True`, so non-testonly targets fail Bazel analysis "
            "when depending on them.",
            f"If `{tname}` must remain non-testonly (e.g. it was not `testonly` "
            "in `BUILD.gn` or is packaged into a non-testonly "
            "`assembly_input_bundle` in `//bundles/assembly/BUILD.bazel`) and "
            "the `<fidl/.../cpp/*test_base.h>` include is unused (or only needs "
            "`<fidl/.../cpp/fidl.h>`), remove the `#include <fidl/.../cpp/"
            f"*test_base.h>` line {src_hint}, remove any `*_cpp_testing` "
            f"dependency and its `# @bazel2gn:skip` directive from `{rel}`, and "
            "note the unused `test_base.h` include removal in the commit body "
            "(`build_only_scope` allows removing unused FIDL `test_base.h` "
            "includes). Otherwise, if the target genuinely subclasses "
            "`fidl::testing::*TestBase` and all its transitive dependents are "
            "`testonly`, set `testonly = True` on the target (and its package "
            "wrappers) and remove `# @bazel2gn:skip` from the `*_cpp_testing` "
            "dependency.",
        )


