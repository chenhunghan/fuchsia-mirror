_CC_HDR_SYNC_RULES = {
    "cc_library",
    "fx_cc_library",
    "idk_cc_source_library",
    "idk_cc_shared_library",
    "idk_cc_static_library",
    "cc_library_zx",
    "cc_shared_library_zx",
}


def _iter_cc_lib_calls(text: str):
    """Yield (rule_name, start_pos, end_pos, is_target_skipped) for C/C++ lib rules."""
    lines = text.splitlines(keepends=True)
    for m in re.finditer(r"(?m)^([A-Za-z_][A-Za-z0-9_]*)\s*\(", text):
        rule_name = m.group(1)
        if rule_name not in _CC_HDR_SYNC_RULES:
            continue
        start_pos = m.start()
        line_idx = text.count("\n", 0, start_pos)
        is_skipped = False
        k = line_idx - 1
        while k >= 0 and lines[k].strip().startswith("#"):
            if re.search(r"#\s*@bazel2gn:skip\b", lines[k]):
                is_skipped = True
                break
            k -= 1
        pos = m.end()
        depth = 1
        n = len(text)
        while pos < n and depth > 0:
            ch = text[pos]
            if ch == "#":
                nl = text.find("\n", pos)
                pos = n if nl == -1 else nl + 1
            elif ch in ('"', "'"):
                q = (
                    text[pos : pos + 3]
                    if text[pos : pos + 3] in ('"""', "'''")
                    else ch
                )
                pos += len(q)
                while pos < n:
                    if text[pos] == "\\":
                        pos += 2
                    elif text.startswith(q, pos):
                        pos += len(q)
                        break
                    else:
                        pos += 1
            elif ch in "([{":
                depth += 1
                pos += 1
            elif ch in ")]}":
                depth -= 1
                pos += 1
            else:
                pos += 1
        yield rule_name, start_pos, pos, is_skipped


def _extract_list_strings(val_text: str) -> set[str]:
    """Extract non-dict-key string literals from an attribute expression."""
    cleaned = re.sub(r"#.*", "", val_text)
    result: set[str] = set()
    for m in re.finditer(r'"([^"]+)"(\s*:)?', cleaned):
        if not m.group(2):
            result.add(m.group(1))
    return result


def _extract_hdrs_entries(
    val_text: str, start_line: int
) -> list[tuple[str, bool, int]]:
    """Return (header_str, is_skipped, line_no) for string entries in hdrs."""
    entries: list[tuple[str, bool, int]] = []
    pending_skip_line: int | None = None
    for idx, raw_line in enumerate(val_text.splitlines()):
        line_no = start_line + idx
        has_inline_skip = bool(re.search(r"#\s*@bazel2gn:skip\b", raw_line))
        stripped = raw_line.strip()
        if stripped.startswith("#"):
            if has_inline_skip:
                pending_skip_line = line_no
            continue
        code_part = re.sub(r"#.*", "", raw_line)
        found_str = False
        for m in re.finditer(r'"([^"]+)"(\s*:)?', code_part):
            if m.group(2):
                continue
            found_str = True
            skip_ln = line_no if has_inline_skip else pending_skip_line
            entries.append((m.group(1), skip_ln is not None, skip_ln or line_no))
        if found_str or (stripped and not stripped.startswith("#")):
            pending_skip_line = None
    return entries


def _parse_cc_call_attrs(text: str, start_pos: int, end_pos: int):
    """Extract target name, srcs strings, and hdrs info from a C/C++ rule call."""
    call_text = text[start_pos:end_pos]
    base_line = text.count("\n", 0, start_pos) + 1
    open_paren = call_text.find("(")
    if open_paren == -1:
        return None, set(), [], None, base_line

    pos = open_paren + 1
    n = len(call_text)
    depth = 1
    target_name = None
    srcs_items: set[str] = set()
    hdrs_items: list[tuple[str, bool, int]] = []
    hdrs_attr_skip_line: int | None = None
    hdrs_attr_line: int = base_line

    while pos < n and depth > 0:
        comment_skip_line: int | None = None
        while pos < n:
            ws_m = re.match(r"[ \t\r\n,]+", call_text[pos:])
            if ws_m:
                pos += ws_m.end()
                continue
            if call_text[pos] == "#":
                nl = call_text.find("\n", pos)
                end_c = n if nl == -1 else nl + 1
                c_line = call_text[pos:end_c]
                if re.search(r"#\s*@bazel2gn:skip\b", c_line):
                    comment_skip_line = base_line + call_text.count("\n", 0, pos)
                pos = end_c
                continue
            break
        if pos >= n or call_text[pos] == ")":
            break

        attr_m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*", call_text[pos:])
        if not attr_m:
            pos += 1
            continue

        attr_name = attr_m.group(1)
        attr_start = pos
        attr_line = base_line + call_text.count("\n", 0, attr_start)
        val_start = pos + attr_m.end()
        pos = val_start

        while pos < n and depth >= 1:
            ch = call_text[pos]
            if depth == 1 and ch in (",", ")"):
                break
            if ch == "#":
                nl = call_text.find("\n", pos)
                pos = n if nl == -1 else nl + 1
            elif ch in ('"', "'"):
                q = (
                    call_text[pos : pos + 3]
                    if call_text[pos : pos + 3] in ('"""', "'''")
                    else ch
                )
                pos += len(q)
                while pos < n:
                    if call_text[pos] == "\\":
                        pos += 2
                    elif call_text.startswith(q, pos):
                        pos += len(q)
                        break
                    else:
                        pos += 1
            elif ch in "([{":
                depth += 1
                pos += 1
            elif ch in ")]}":
                depth -= 1
                pos += 1
            else:
                pos += 1

        val_text = call_text[val_start:pos]
        first_nl = call_text.find("\n", attr_start)
        first_line = (
            call_text[attr_start:]
            if first_nl == -1
            else call_text[attr_start:first_nl]
        )
        if re.search(r"#\s*@bazel2gn:skip\b", first_line):
            comment_skip_line = attr_line

        if attr_name == "name":
            nm = re.search(r'"([^"]+)"', val_text)
            if nm:
                target_name = nm.group(1)
        elif attr_name == "srcs":
            srcs_items = _extract_list_strings(val_text)
        elif attr_name == "hdrs":
            hdrs_attr_line = attr_line
            hdrs_attr_skip_line = comment_skip_line
            val_line = base_line + call_text.count("\n", 0, val_start)
            hdrs_items = _extract_hdrs_entries(val_text, val_line)

    return (
        target_name,
        srcs_items,
        hdrs_items,
        hdrs_attr_skip_line,
        hdrs_attr_line,
    )


def check_cc_hdrs_skip_and_srcs_duplication(d: str, rel: str, text: str) -> None:
    """Flag unnecessary # @bazel2gn:skip on C/C++ `hdrs` and duplicate srcs/hdrs."""
    base_bazel = base_text(rel)
    base_skipped_targets: set[str] = set()
    base_dup_pairs: set[tuple[str, str]] = set()
    if base_bazel:
        for _, b_start, b_end, _ in _iter_cc_lib_calls(base_bazel):
            b_name, b_srcs, b_hdrs, b_attr_skip, _ = _parse_cc_call_attrs(
                base_bazel, b_start, b_end
            )
            if not b_name:
                continue
            if b_attr_skip is not None or any(sk for _, sk, _ in b_hdrs):
                base_skipped_targets.add(b_name)
            for h, _, _ in b_hdrs:
                if h in b_srcs:
                    base_dup_pairs.add((b_name, h))

    gn_rel = "BUILD.gn" if d == "." else f"{d}/BUILD.gn"
    gn_ref_text = base_text(gn_rel)
    if not gn_ref_text and os.path.isfile(gn_rel):
        try:
            with open(gn_rel, encoding="utf-8", errors="replace") as f:
                gn_ref_text = f.read()
        except OSError:
            gn_ref_text = ""

    for rule_name, start_pos, end_pos, is_target_skipped in _iter_cc_lib_calls(
        text
    ):
        (
            target_name,
            srcs_items,
            hdrs_items,
            hdrs_attr_skip_line,
            hdrs_attr_line,
        ) = _parse_cc_call_attrs(text, start_pos, end_pos)
        if not target_name:
            continue

        dup_hdrs = sorted(
            {
                h
                for h, _, _ in hdrs_items
                if h in srcs_items and (target_name, h) not in base_dup_pairs
            }
        )

        if not is_target_skipped and target_name not in base_skipped_targets:
            syncable_skips: list[tuple[str, int]] = []
            for h, is_item_sk, item_ln in hdrs_items:
                if hdrs_attr_skip_line is None and not is_item_sk:
                    continue
                in_gn = (
                    not gn_ref_text
                    or f'"{h}"' in gn_ref_text
                    or f'"{os.path.basename(h)}"' in gn_ref_text
                )
                if h in srcs_items or (not h.startswith("//") and in_gn):
                    syncable_skips.append(
                        (h, hdrs_attr_skip_line or item_ln)
                    )

            if syncable_skips or (
                hdrs_attr_skip_line is not None and not hdrs_items
            ):
                finding_line = (
                    hdrs_attr_skip_line
                    if hdrs_attr_skip_line is not None
                    else syncable_skips[0][1]
                )
                findings[:] = [
                    f
                    for f in findings
                    if not (
                        f.get("category") == "undocumented_bazel2gn_directive"
                        and f.get("file") == rel
                        and f.get("line") == finding_line
                    )
                ]
                sync_names = ", ".join(f'`"{h}"`' for h, _ in syncable_skips)
                dup_names = ", ".join(f'`"{h}"`' for h in dup_hdrs)
                if dup_hdrs:
                    msg = (
                        f"Target '{target_name}' ({rule_name}) annotates `hdrs` "
                        f"with `# @bazel2gn:skip` while listing {dup_names} in "
                        f"`srcs`. `bazel2gn` natively translates `hdrs` to "
                        f"`public` in `BUILD.gn`, so skipping `hdrs` and "
                        f"duplicating public headers in `srcs` is unnecessary."
                    )
                    rem = (
                        f"Drop `# @bazel2gn:skip` (and any accompanying comment) "
                        f"from `hdrs` on '{target_name}', remove {dup_names} "
                        f"from `srcs` so public headers are listed only in "
                        f"`hdrs`, and re-run `fx bazel2gn` (then verify the "
                        f"regenerated `BUILD.gn` builds and passes `gn check`)."
                    )
                else:
                    msg = (
                        f"Target '{target_name}' ({rule_name}) annotates `hdrs` "
                        f"with `# @bazel2gn:skip` ({sync_names or 'empty hdrs'}), "
                        f"but `bazel2gn` natively translates `hdrs` to `public` "
                        f"in `BUILD.gn`."
                    )
                    rem = (
                        f"Drop `# @bazel2gn:skip` (and any accompanying comment) "
                        f"from `hdrs` on '{target_name}' so `bazel2gn` handles "
                        f"`hdrs`, then re-run `fx bazel2gn` and verify the "
                        f"regenerated `BUILD.gn` builds and passes `gn check`."
                    )
                findings.append(
                    {
                        "category": "redundant_hdrs_bazel2gn_skip",
                        "severity": "ERROR",
                        "file": rel,
                        "line": finding_line,
                        "message": msg,
                        "remediation": rem,
                    }
                )
                continue

        if dup_hdrs:
            dup_names = ", ".join(f'`"{h}"`' for h in dup_hdrs)
            findings.append(
                {
                    "category": "duplicate_header_in_srcs_and_hdrs",
                    "severity": "ERROR",
                    "file": rel,
                    "line": hdrs_attr_line,
                    "message": (
                        f"Target '{target_name}' ({rule_name}) lists {dup_names} "
                        f"in both `srcs` and `hdrs`. In Bazel C/C++ library "
                        f"rules, headers in `hdrs` are already compiled and "
                        f"exported (`bazel2gn` maps `hdrs` to `public` and "
                        f"`srcs` to `sources`)."
                    ),
                    "remediation": (
                        f"Keep {dup_names} only in `hdrs` on '{target_name}' "
                        f"and remove the duplicate entry from `srcs` (then "
                        f"re-run `fx bazel2gn` if `BUILD.gn` is synced)."
                    ),
                }
            )


