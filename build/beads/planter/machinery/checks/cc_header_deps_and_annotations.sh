# Extract contiguous `#` comment blocks with indentation and following line info.
def _extract_comment_blocks(src):
    lines = src.splitlines()
    blocks = []
    i = 0
    while i < len(lines):
        stripped = lines[i].lstrip()
        if not stripped.startswith("#"):
            i += 1
            continue
        start = i
        lead_indent = len(lines[i]) - len(stripped)
        raw = []
        while i < len(lines) and lines[i].lstrip().startswith("#"):
            raw.append(lines[i].lstrip())
            i += 1
        end = i - 1
        k = i
        while k < len(lines) and not lines[k].strip():
            k += 1
        next_idx = k if k < len(lines) else None
        next_line = lines[k] if k < len(lines) else ""
        blocks.append((start, end, lead_indent, raw, next_idx, next_line))
    return blocks


GN_RETENTION_COMMENT_RE = re.compile(
    r"\b(?:(?:retained|kept|stay(?:s|ing)?|remain(?:s|ing)?)"
    r"(?:\s+(?:hand[- ]written|manual(?:ly)?))?\s+in\s+(?:gn|build\.gn)"
    r"|keep\b[^\n]*\bin\s+(?:gn|build\.gn))\b",
    re.I,
)

GN_TEMPLATE_GENERATED_COMMENT_RE = re.compile(
    r"(?:\b\w+\.gn\.tmpl|\bgenerated\s+by\s+the\s+`?fx\s+create`?\b"
    r"|\bgenerated\s+by\s+//[^\s`'\"]+\.py\b)",
    re.I,
)


# Return significant prose tokens for a comment block, or empty set for boilerplate.
def _substantive_comment_tokens(raw_lines, require_multiline=True):
    bodies = [
        ln.lstrip("#").strip()
        for ln in raw_lines
        if ln.lstrip("#").strip()
        and not DIRECTIVE_RE.search(ln)
        and "LINT.IfChange" not in ln
        and "LINT.ThenChange" not in ln
    ]
    if require_multiline and (len(bodies) < 3 or sum(len(b) for b in bodies) < 120):
        return set()
    joined = " ".join(bodies)
    low = joined.lower()
    if "copyright " in low and (
        "all rights reserved" in low
        or "bsd-style license" in low
        or "license file" in low
    ):
        return set()
    if GN_RETENTION_COMMENT_RE.search(joined) or GN_TEMPLATE_GENERATED_COMMENT_RE.search(joined):
        return set()
    if any(
        marker in joined
        for marker in (
            "BAZEL2GN SENTINEL",
            "AUTO-GENERATED",
            "Assignment had no effect",
        )
    ):
        return set()
    code_like = sum(
        1
        for b in bodies
        if b.endswith(("{", "}", "[", "]", ","))
        or b.startswith(('"//', '":', "import("))
    )
    if bodies and code_like * 2 >= len(bodies):
        return set()
    tokens = {
        w
        for w in re.findall(r"[a-z][a-z0-9_]{3,}", low)
        if w not in GN_COMMENT_STOPWORDS
    }
    if require_multiline and len(tokens) < 8:
        return set()
    return tokens


# Return the hand-written prefix of a BUILD.gn file above any bazel2gn sentinel.
def _handwritten_gn_prefix(gn_text):
    sentinel = "## BAZEL2GN SENTINEL"
    idx = gn_text.find(sentinel)
    return gn_text[:idx] if idx >= 0 else gn_text


# Locate an un-commented Bazel list attribute inside a top-level rule call.
def _find_attr_line_in_call(bz_lines, call_idx, mapped_attrs):
    depth = 0
    for j in range(call_idx, len(bz_lines)):
        line = bz_lines[j]
        code = line.split("#", 1)[0]
        if depth == 1:
            m = re.match(r"^\s+([a-z_][a-z0-9_]*)\s*=\s*\[", line)
            if m and m.group(1) in mapped_attrs:
                has_attr_comment = j > 0 and bz_lines[j - 1].lstrip().startswith("#")
                return j + 1, m.group(1), has_attr_comment
        depth += code.count("(") - code.count(")")
        if depth <= 0 and j > call_idx:
            break
    return None, None, False


# Check multi-line explanatory comments dropped or misplaced when migrating BUILD.gn.
def check_dropped_gn_comments(d, rel, text):
    gn_rel = os.path.join(d, "BUILD.gn")
    base_gn = _handwritten_gn_prefix(base_text(gn_rel))
    if not base_gn:
        return
    cur_gn_path = os.path.join(workdir, gn_rel)
    cur_gn = ""
    if os.path.isfile(cur_gn_path):
        with open(cur_gn_path, encoding="utf-8", errors="replace") as gf:
            cur_gn = _handwritten_gn_prefix(gf.read())

    retained_gn_sets = [
        _substantive_comment_tokens(blk[3], require_multiline=False)
        for blk in _extract_comment_blocks(cur_gn)
    ]
    bz_lines = text.splitlines()
    bz_blocks = [
        (blk, _substantive_comment_tokens(blk[3], require_multiline=False))
        for blk in _extract_comment_blocks(text)
    ]

    for start, end, lead_indent, raw, _, next_line in _extract_comment_blocks(base_gn):
        gn_tokens = _substantive_comment_tokens(raw, require_multiline=True)
        if not gn_tokens:
            continue
        if any(len(gn_tokens & rset) / len(gn_tokens) >= 0.65 for rset in retained_gn_sets):
            continue

        best_blk = None
        best_recall = 0.0
        for blk, btokens in bz_blocks:
            recall = len(gn_tokens & btokens) / len(gn_tokens)
            if recall > best_recall:
                best_recall = recall
                best_blk = blk

        attr_m = re.match(r"^\s*([a-z_][a-z0-9_]*)\s*\+?=", next_line)
        gn_attr = attr_m.group(1) if attr_m else ""
        mapped_attrs = GN_TO_BAZEL_LIST_ATTRS.get(gn_attr, ())
        gn_span = f"{gn_rel}:{start + 1}-{end + 1}"
        quoted_block = "\n".join(f"    {ln}" for ln in raw)

        if best_recall < 0.65:
            target_line = 1
            placement_hint = f"on the migrated target in `{rel}`"
            if best_blk is not None and best_recall >= 0.20:
                target_line = best_blk[0] + 1
                if best_blk[4] is not None and mapped_attrs:
                    attr_line, bz_attr, _ = _find_attr_line_in_call(
                        bz_lines, best_blk[4], mapped_attrs
                    )
                    if attr_line is not None:
                        target_line = attr_line
                        placement_hint = (
                            f"indented directly above `{bz_attr} = [` in `{rel}` "
                            f"(removing the abbreviated summary at line {best_blk[0] + 1})"
                        )
            elif mapped_attrs:
                placement_hint = (
                    f"indented directly above `{mapped_attrs[0]} = [` on the "
                    f"migrated target in `{rel}` (where `{gn_attr}` was moved)"
                )
            msg = (
                f"Multi-line explanatory comment from `{gn_span}`"
                + (f" (above `{gn_attr}`)" if gn_attr else "")
                + f" was lost or overly condensed in `{rel}`."
            )
            rem = (
                f"Preserve the full original comment block from `{gn_span}` verbatim "
                f"and place it {placement_hint}:\n{quoted_block}"
            )
            _emit(
                findings,
                "dropped_gn_comment_block",
                "WARNING",
                rel,
                target_line,
                msg,
                rem,
            )
        elif (
            lead_indent > 0
            and mapped_attrs
            and best_blk is not None
            and best_blk[2] == 0
            and best_blk[4] is not None
        ):
            attr_line, bz_attr, has_attr_comment = _find_attr_line_in_call(
                bz_lines, best_blk[4], mapped_attrs
            )
            if attr_line is not None and not has_attr_comment:
                msg = (
                    f"Comment block from `{gn_span}` documented `{gn_attr}`, so it "
                    f"belongs directly above `{bz_attr} = [` (line {attr_line}) "
                    f"rather than above the outer rule call at line {best_blk[0] + 1}."
                )
                rem = (
                    f"Move the comment block from lines {best_blk[0] + 1}-"
                    f"{best_blk[1] + 1} inside the target call, indented 4 spaces "
                    f"directly above `{bz_attr} = [` at line {attr_line}."
                )
                _emit(
                    findings,
                    "dropped_gn_comment_block",
                    "WARNING",
                    rel,
                    attr_line,
                    msg,
                    rem,
                )


# Check for @bazel2gn directives that re-map external repo labels bazel2gn
# already translates via its built-in third-party label map. The map is read
# from the checkout at runtime so this check never hardcodes repository names.
BUILTIN_LABEL_MAP_REL = "build/tools/bazel2gn/third_party_target_map.json"
QUOTED_LABEL_RE = re.compile(r'"([^"\s]+)"')

BUILTIN_LABEL_REMEDIATION = """\
bazel2gn already translates this external Bazel label to its GN label through
its built-in map (build/tools/bazel2gn/third_party_target_map.json). Remove the
`# @bazel2gn:` directive (and its explanatory comment), keep the plain Bazel label
in the list, and rerun `fx bazel2gn` to confirm the generated BUILD.gn is unchanged.
Only add a directive when the generated GN label actually differs from the GN dep."""


def load_builtin_label_map():
    path = os.path.join(workdir, BUILTIN_LABEL_MAP_REL)
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def next_code_line(lines, idx):
    for j in range(idx + 1, len(lines)):
        s = lines[j].strip()
        if s and not s.startswith("#"):
            return j
    return None


# Return the external label that the `# @bazel2gn:` directive at `lines[i]` overrides
# although bazel2gn already maps it via `label_map`, inspecting the directive itself
# (inline form) and the entry it annotates; else None.
def _redundant_builtin_label_hit(lines, i, label_map):
    if not label_map:
        return None
    candidates = [lines[i]]
    j = next_code_line(lines, i)
    if j is not None:
        candidates.append(lines[j])
    for cand in candidates:
        hit = next((l for l in QUOTED_LABEL_RE.findall(cand) if l in label_map), None)
        if hit:
            return hit
    return None


def check_redundant_builtin_label_directives(d, rel, text, label_map):
    if not label_map:
        return
    base_lines = set(l.strip() for l in base_text(rel).splitlines())
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = DIRECTIVE_RE.search(line)
        if not m or line.strip() in base_lines:
            continue
        hit = _redundant_builtin_label_hit(lines, i, label_map)
        if not hit:
            continue
        _emit(
            findings,
            "redundant_builtin_label_directive",
            "ERROR",
            rel,
            i + 1,
            f"`# @bazel2gn:{m.group(1)}` directive overrides `{hit}`, which bazel2gn "
            f"already maps to `{label_map[hit]}`.",
            BUILTIN_LABEL_REMEDIATION,
        )


# Check whether any C/C++ source or header in package `d` uses an angled
# workspace-root-relative `#include <...>` (e.g. `#include <src/lib/...>`),
# which Bazel's default `-iquote .` does not search and which empty
# `//build/config:default_include_dirs` does not add to `-I`.
def _pkg_has_angled_workspace_root_include(d):
    pkg_abs = os.path.join(workdir, d)
    if not os.path.isdir(pkg_abs):
        return False
    cc_exts = (".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".hh")
    ang_re = re.compile(r"^\s*#\s*include\s*<([^>]+)>", re.M)
    for root, _, files in os.walk(pkg_abs):
        for fn in files:
            if not fn.endswith(cc_exts):
                continue
            fpath = os.path.join(root, fn)
            try:
                with open(fpath, encoding="utf-8", errors="replace") as sf:
                    content = sf.read()
            except OSError:
                continue
            for inc in ang_re.findall(content):
                if "/" in inc and os.path.isfile(os.path.join(workdir, inc)):
                    return True
    return False


# Return `(output_name, rule_name)` when `lines[i]` is a
# `# @bazel2gn:raw_attribute:output_name` directive on a rule for which
# bazel_minimality requires removing it (fx_cc_binary / fx_cc_test_binary /
# fx_cc_test natively support `gn_output_name`; Rust tests are renamed instead);
# else None.
def _raw_output_name_on_native_rule(lines, i):
    m = re.search(
        r'#\s*@bazel2gn:raw_attribute:\s*output_name\s*=\s*"([^"]+)"', lines[i]
    )
    if not m:
        return None
    j = next_code_line(lines, i)
    if j is None:
        return None
    rm = re.match(
        r"^\s*(fx_cc_binary|fx_cc_test_binary|fx_cc_test|rustc_test|rust_test|"
        r"host_rustc_test)\(\s*$",
        lines[j],
    )
    if not rm:
        return None
    return m.group(1), rm.group(1)


# Rules that bazel2gn maps to `noGNEquivalent` (it already ignores them), parsed from
# the checkout's build/tools/bazel2gn sources the same way migration_sanity does.
def _load_no_gn_equiv_rules():
    b2gn_dir = os.path.join(workdir, "build", "tools", "bazel2gn")
    rules = set()
    try:
        names = sorted(os.listdir(b2gn_dir))
    except OSError:
        return rules
    for fn in names:
        if not fn.endswith(".go") or fn.endswith("_test.go"):
            continue
        try:
            with open(os.path.join(b2gn_dir, fn), encoding="utf-8") as gf:
                src = gf.read()
        except OSError:
            continue
        rules.update(re.findall(r'"([A-Za-z0-9_]+)"\s*:\s*noGNEquivalent\b', src))
    return rules


NO_GN_EQUIV_BAZEL_RULES = _load_no_gn_equiv_rules()


# True when `lines[i]` is a `# @bazel2gn:skip` directly above a call to a rule that
# bazel2gn already ignores (migration_sanity redundant_bazel2gn_skip removes it).
def _skip_on_no_gn_equiv_rule(lines, i):
    m = DIRECTIVE_RE.search(lines[i])
    if not m or m.group(1) != "skip" or not lines[i].strip().startswith("#"):
        return False
    j = next_code_line(lines, i)
    if j is None:
        return False
    rm = re.match(r"^\s*([A-Za-z_]\w*)\(", lines[j])
    return bool(rm and rm.group(1) in NO_GN_EQUIV_BAZEL_RULES)


# True when `lines[i]` is a `# @bazel2gn:skip` directly above a Bazel `test_suite()`
# target (which is always skipped from bazel2gn in dual-build packages and does
# not need an extra justifying comment).
def _skip_on_bazel_test_suite(lines, i):
    m = DIRECTIVE_RE.search(lines[i])
    if not m or m.group(1) != "skip" or not lines[i].strip().startswith("#"):
        return False
    j = next_code_line(lines, i)
    return j is not None and bool(re.match(r"^\s*test_suite\(", lines[j]))


# Check for undocumented or unskipped `copts = ["-I."]` on fx_cc_* targets.
def check_fx_cc_output_name_and_default_include_dirs(d, rel, text):
    lines = text.splitlines()
    has_angled_ws_inc = _pkg_has_angled_workspace_root_include(d)
    fx_cc_re = re.compile(r"^(fx_cc_library|fx_cc_binary|fx_cc_test)\(\s*$", re.M)
    for m in fx_cc_re.finditer(text):
        rule_name = m.group(1)
        block = block_at(text, m.end() - 1)
        copts = list_attr(block, "copts")
        if "-I." not in copts:
            continue
        name_m = re.search(r'^\s+name\s*=\s*"([^"]+)"', block, re.M)
        tname = name_m.group(1) if name_m else "?"
        copt_m = re.search(r"^\s+copts\s*=\s*\[", block, re.M)
        target_line_idx = text[: m.start()].count("\n")
        copt_line_idx = (
            text[: m.end() - 1 + copt_m.start()].count("\n")
            if copt_m
            else target_line_idx
        )
        line_no = copt_line_idx + 1
        if not has_angled_ws_inc:
            _emit(
                findings,
                "copts_default_include_dirs",
                "ERROR",
                rel,
                line_no,
                f'`{rule_name}(name = "{tname}")` sets `"-I."` in `copts`, but no '
                f"source or header in `{d}` uses an angled workspace-root "
                "`#include <...>` and Bazel already sets `-iquote .` for the "
                "workspace root.",
                f'Remove `"-I."` from `copts` on `{rule_name}(name = "{tname}")` '
                f"in `{rel}`.",
            )
            continue
        has_comment = documented(lines, copt_line_idx) or documented(
            lines, target_line_idx
        )
        if not has_comment:
            _emit(
                findings,
                "copts_default_include_dirs",
                "WARNING",
                rel,
                line_no,
                f'`{rule_name}(name = "{tname}")` sets `"-I."` in `copts` without '
                "a comment explaining which angled workspace-root `#include <...>` "
                "requires `-I.` (since `//build/config:default_include_dirs` is "
                "empty in Bazel and `-iquote .` only searches quoted includes).",
                f"Add a brief comment directly above `copts = [\"-I.\"]` on "
                f'`{rule_name}(name = "{tname}")` in `{rel}` naming the header '
                "with the angled workspace-root `#include <...>`.",
            )


# Check for stale GN-retention comments copied onto Bazel targets in BUILD.bazel.
def check_stale_gn_retention_comments(d, rel, text):
    base_src = base_text(rel)
    base_blocks = {
        "\n".join(ln.strip() for ln in blk[3])
        for blk in _extract_comment_blocks(base_src)
    }
    gn_path = os.path.join(workdir, d, "BUILD.gn")
    has_dual_build_sentinel = False
    if os.path.isfile(gn_path):
        try:
            with open(gn_path, encoding="utf-8", errors="replace") as gf:
                has_dual_build_sentinel = "BAZEL2GN SENTINEL" in gf.read()
        except OSError:
            has_dual_build_sentinel = False
    for start, end, _, raw, next_idx, next_line in _extract_comment_blocks(text):
        norm_blk = "\n".join(ln.strip() for ln in raw)
        if norm_blk in base_blocks:
            continue
        if next_idx is None or not re.match(r"^\s*[a-z_][a-z0-9_]*\(\s*$", next_line):
            continue
        if re.match(r"^\s*package\(\s*$", next_line):
            continue
        hit_line = None
        for offset, ln in enumerate(raw):
            if DIRECTIVE_RE.search(ln):
                continue
            if GN_RETENTION_COMMENT_RE.search(ln):
                hit_line = start + offset + 1
                break
        if hit_line is None:
            continue
        has_skip = any(
            m.group(1) == "skip"
            for ln in raw
            for m in [DIRECTIVE_RE.search(ln)]
            if m
        )
        # Allow newly authored comments above `# @bazel2gn:skip` in dual-build packages
        # that explain why bazel2gn skips generating the target above the GN sentinel.
        joined_low = " ".join(ln.lstrip("#").strip() for ln in raw).lower()
        if (
            has_skip
            and has_dual_build_sentinel
            and ("bazel2gn" in joined_low or "sentinel" in joined_low)
        ):
            continue
        if has_skip:
            rem = (
                f"In `{rel}` (lines {start + 1}-{end + 1}), replace the stale "
