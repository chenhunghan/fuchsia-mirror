def check_gn_template_generated_comments(d, rel, text):
    for start, end, _, raw, _, _ in _extract_comment_blocks(text):
        hit_line = None
        for offset, ln in enumerate(raw):
            if DIRECTIVE_RE.search(ln):
                continue
            if GN_TEMPLATE_GENERATED_COMMENT_RE.search(ln):
                hit_line = start + offset + 1
                break
        if hit_line is None:
            continue
        rem = (
            f"Remove the GN scaffolding/template generation comment block from "
            f"`{rel}` (lines {start + 1}-{end + 1}); `{rel}` is a Bazel build "
            "file and was not generated from a `BUILD.gn.tmpl` template."
