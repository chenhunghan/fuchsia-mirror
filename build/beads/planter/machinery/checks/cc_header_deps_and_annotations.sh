                f"(lines {start + 1}-{end + 1}). Once all deterministic checks pass, "
                "dispute any resulting `review_diff/dropped_comment` false positive "
                "in `CoderReport.disputed_findings`."
            )
        elif has_skip:
            msg = (
                f"Comment in `{rel}` describes a Bazel target in `BUILD.bazel` as "
                "retained or staying in GN (`BUILD.gn`)."
            )
            rem = (
                f"In `{rel}` (lines {start + 1}-{end + 1}), replace the stale "
                '"Retained in GN / stay in GN" wording above `# @bazel2gn:skip` '
                "with a concise comment stating why `bazel2gn` skips generating "
                "the GN target (for example, because `bazel2gn` does not convert "
                "the rule and a hand-written target remains in `BUILD.gn`), while "
                "preserving any general domain description of the component/target."
            )
        else:
            msg = (
                f"Comment in `{rel}` describes a Bazel target in `BUILD.bazel` as "
                "retained or staying in GN (`BUILD.gn`)."
            )
            rem = (
                f"Remove the obsolete GN-retention comment lines from `{rel}` "
                f"(lines {start + 1}-{end + 1}); the target is now migrated to "
                "`BUILD.bazel` and is no longer retained only in `BUILD.gn`."
            )
        _emit(
            findings,
            "stale_gn_retention_comment_in_bazel",
            "ERROR",
            rel,
            hit_line,
            msg,
            rem,
        )


