"""Runs python_mobly_test() targets end to end, without any device.

This checks that //tools/mobly_test_parser runs the Mobly driver, which runs
the Mobly test py_binary() directly, all from the host test's runtime
directory, with the arguments generated by python_mobly_test(). No device is
needed since the tests pass their own Mobly config with `local_config_source`,
whose testbed has no controllers.
"""

import os
import subprocess
import tempfile
import unittest

import python.runfiles.runfiles as runfiles

# The host test wrapper scripts to invoke, which must be listed in the test's
# `test_data`.
_PACKAGE_RLOCATION = (
    "_main/build/bazel/rules/host_tests/tests/python_mobly_test"
)
_ALL_OPTIONS_TEST = f"{_PACKAGE_RLOCATION}/fake_mobly_test_all_options"
_CUSTOM_TEST = f"{_PACKAGE_RLOCATION}/fake_mobly_test_custom"
_TIMEOUT_TEST = f"{_PACKAGE_RLOCATION}/fake_mobly_timeout_test"


class FakeMoblyTestE2eTest(unittest.TestCase):
    def _run_host_test(
        self,
        rlocation: str,
        *args: str,
        test_outdir: str | None = None,
        expect_success: bool = True,
    ) -> subprocess.CompletedProcess[str]:
        r = runfiles.Create()
        assert r is not None, "Cannot find runfiles"
        test_script = r.Rlocation(rlocation)
        assert test_script is not None and os.path.exists(
            test_script
        ), f"Cannot find {rlocation} in runfiles"
        with tempfile.TemporaryDirectory() as tmp_dir:
            env = dict(os.environ)
            env.update(r.EnvVars())
            # Set on infra bots, makes the Mobly driver ignore
            # `--config-yaml-path` and look for real devices.
            env.pop("FUCHSIA_TESTBED_CONFIG", None)
            # Set by Fuchsia test runners, required by the Mobly driver.
            env["FUCHSIA_TEST_OUTDIR"] = test_outdir or tmp_dir
            result = subprocess.run(
                [test_script, *args],
                env=env,
                text=True,
                capture_output=True,
            )
        if expect_success:
            self.assertEqual(
                result.returncode,
                0,
                f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}",
            )
        return result

    def test_list_mobly_tests(self) -> None:
        result = self._run_host_test(_ALL_OPTIONS_TEST, "--list_mobly_tests")
        self.assertIn("==========> FakeMoblyTest <==========", result.stdout)
        self.assertIn("\ntest_pass\n", result.stdout)

    def test_run_mobly_test(self) -> None:
        # Runs with the Mobly config (-c), --test_cases and --v arguments
        # generated by python_mobly_test(), which --list_mobly_tests skips.
        result = self._run_host_test(_ALL_OPTIONS_TEST)
        output = result.stdout + result.stderr
        self.assertIn("[Test] test_pass PASS", output)
        self.assertIn(
            "Error 0, Executed 1, Failed 0, Passed 1, Requested 1, Skipped 0",
            output,
        )

    def test_run_mobly_test_with_custom_main_callable_and_libraries(
        self,
    ) -> None:
        # The test calls its custom `main_callable` and imports a library
        # from `libraries`.
        result = self._run_host_test(_CUSTOM_TEST)
        output = result.stdout + result.stderr
        self.assertIn("[Test] test_helper PASS", output)
        self.assertIn("Executed 1, Failed 0, Passed 1", output)

    def test_timeout_sends_sigterm_to_mobly_test(self) -> None:
        # The test outlives its timeout. mobly_driver must send SIGTERM to the
        # Mobly test process itself (not only to its py_binary() launcher)
        # and give it its cleanup period, which is longer than the 1s given
        # to leftover processes before SIGKILL.
        with tempfile.TemporaryDirectory() as test_outdir:
            result = self._run_host_test(
                _TIMEOUT_TEST, test_outdir=test_outdir, expect_success=False
            )
            output = f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
            self.assertNotEqual(result.returncode, 0, output)
            self.assertIn("Sending SIGTERM to begin cleanup period.", output)
            # Logged by Mobly in the test process when it gets the SIGTERM.
            self.assertIn(
                "Test received a SIGTERM. Aborting all tests.", output
            )
            # Written by teardown_test, which takes longer than the 1s given
            # to leftover processes before SIGKILL.
            self.assertTrue(
                os.path.exists(os.path.join(test_outdir, "cleanup_done")),
                f"Missing cleanup_done marker.\n{output}",
            )
