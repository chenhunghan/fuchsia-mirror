    /// Exits the current process with the given return code. Does not return.
    ///
    /// # Panics
    ///
    /// Panics if the calling thread is not a user thread.
    ///
    /// # Safety
    ///
    /// The caller must uphold the [`ThreadDispatcher::exit_current`] preconditions (the calling
